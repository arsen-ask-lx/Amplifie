/** Относительная яркость по WCAG 2.x. */
function luminance(hex: string): number {
  const channel = (at: number) => {
    const value = Number.parseInt(hex.slice(at, at + 2), 16) / 255;
    return value <= 0.03928 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * channel(1) + 0.7152 * channel(3) + 0.0722 * channel(5);
}

/** Во сколько раз одно светлее другого — то же число, что считает `make contrast`. */
export function contrastRatio(one: string, other: string): number {
  const [light, dark] = [luminance(one), luminance(other)].sort((a, b) => b - a);
  return ((light ?? 0) + 0.05) / ((dark ?? 0) + 0.05);
}

/**
 * Каким цветом рисовать значок на заливке: белым или чёрным.
 *
 * ⚠️ СЧИТАЕТСЯ, А НЕ ВЫБИРАЕТСЯ НАБОРОМ. Цвет заливки называет человек
 * пипеткой, и заранее его не проверит никакой гейт. Считаем обе пары
 * и берём ту, что читается лучше, — так делают метки GitHub. На любом
 * из 16 млн цветов лучшая пара не ниже 3:1 — это проверено перебором
 * куба RGB в `projectLook.test.ts`, а не обещано словами.
 */
export function inkOn(background: string): "#ffffff" | "#000000" {
  return contrastRatio("#ffffff", background) >= contrastRatio("#000000", background)
    ? "#ffffff"
    : "#000000";
}

