/**
 * Что бек и фронт обязаны понимать одинаково: стадии задачи и размыкатель.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ПАКЕТ. До task-012 список стадий жил в трёх местах —
 * CHECK в миграции, `STAGES` на беке, `COLUMNS` во фронте, — а размыкатель
 * в двух, причём совпадение второго было оформлено комментарием
 * «Совпадает с сервером». Комментарий — это не единственный источник
 * правды, это надежда на внимательность.
 *
 * ⚠️ ЧЕТВЁРТАЯ СТОРОНА — SQL, И ОНА ИМПОРТОМ НЕ БЕРЁТСЯ. Настоящий сторож
 * списка стоит в базе: `CHECK task_stage_known`. Миграция — текст, и свести
 * её к этому объявлению нельзя. Поэтому совпадение проверяет гейт
 * `make stages`, который читает обе стороны. Без него мы бы переставили
 * копию и решили, что убрали её.
 */

/**
 * Стадии в порядке движения. Порядок — часть знания: по нему доска
 * решает, куда можно подвинуть влево и вправо.
 *
 * ⚠️ Читается гейтом ТЕКСТОМ (`export const STAGES = [ ... ]`), потому
 * что вторая сторона — SQL. Форму объявления менять нельзя, не поправив
 * `tools/checks/check-stages.mjs`.
 */
export const STAGES = ["к работе", "в работе", "на проверке", "готово", "отменена"] as const;

export type Stage = (typeof STAGES)[number];

/**
 * Стадия, с которой задача начинается. Совпадает с DEFAULT в базе.
 */
export const FIRST_STAGE: Stage = "к работе";

/**
 * Стадия, которую доска не показывает. Задача при этом не удаляется:
 * «решили не делать» — тоже исход, и он должен остаться виден в списке.
 */
export const HIDDEN_STAGE: Stage = "отменена";

/**
 * Сколько отказов подряд размыкают прогон агента.
 *
 * Правило проекта требует три попытки; здесь взято строже намеренно
 * (task-011): у каждой попытки цена в деньгах и секундах, а третья почти
 * никогда не отличается от второй.
 *
 * ⚠️ ЧЕСТНО О СЛАБОСТИ: у этого числа нет второй стороны в SQL, и сверить
 * его не с чем. Единственность держится только тем, что объявление одно.
 * Это слабее, чем у стадий, и сказано вслух, а не выдано за проверенное.
 */
export const BREAKER = 2;

export function isStage(value: string): value is Stage {
  return (STAGES as readonly string[]).includes(value);
}
