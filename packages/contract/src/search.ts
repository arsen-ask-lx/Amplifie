/**
 * Как строка человека становится словами поиска (task-100).
 *
 * ⚠️ В ОБЩЕМ ПАКЕТЕ, ПОТОМУ ЧТО ЭТО ДОГОВОР. Сервер ищет по этим словам,
 * а клиент подсвечивает ими найденное. Держи они по своей копии — однажды
 * разойдутся молча: сервер найдёт реплику по «ёлке», а клиент подсветит
 * не то или ничего.
 */

/** Слов в запросе. Больше — это уже не поиск, а вставленный абзац. */
const MAX_WORDS = 8;

/**
 * Короче — не ищем: одна буква раскрылась бы началом слова во весь словарь,
 * и частое слово дорого (замер шага 0 task-100).
 */
const MIN_WORD = 2;

/** Нижний регистр и ё как е — одна нормализация на слова и на текст. */
export function searchFold(text: string): string {
  return text.toLowerCase().replaceAll("ё", "е");
}

/**
 * Строка человека → слова запроса.
 *
 * Только буквы и цифры: операторы поиска Postgres (`&`, `|`, `!`, `:*`, `<->`,
 * кавычки) в слово не попадают по построению, и собранный запрос не может
 * стать синтаксической ошибкой. Подчёркивание делит слово — так же его делит
 * разбор Postgres, и «код_ошибки» ищется обоими словами.
 */
export function searchWords(q: string): string[] {
  const words = searchFold(q)
    .split(/[^\p{L}\p{N}]+/u)
    .filter((word) => word.length >= MIN_WORD);
  return [...new Set(words)].slice(0, MAX_WORDS);
}
