/**
 * Как записано упоминание человека (Р-031).
 *
 * ⚠️ ЖИВЁТ В ОБЩЕМ ПАКЕТЕ, ПОТОМУ ЧТО ЭТО ДОГОВОР, А НЕ УДОБСТВО.
 * Записывает упоминание фронт, а читает и проверяет права по нему бек.
 * Держи они по своей копии — разойдутся молча: фронт напишет упоминание
 * чуть иначе, бек его не увидит, и человек будет звать коллегу, а тот
 * не получит ничего. Ни ошибки, ни следа.
 *
 * Запись нарочно совпадает по форме с нашей ссылкой — `[подпись](адрес)`.
 * Клиент, который про упоминания не знает, покажет её ссылкой, а не
 * мусором: текст остаётся читаемым.
 */

/**
 * Номер участника — ровно UUID, и это главная строгость всей записи.
 *
 * ⚠️ БЕЗ НЕЁ УПОМИНАНИЕМ СТАНОВИТСЯ ЛЮБАЯ СКОБКА С СОБАЧКОЙ. В переписке
 * пишут `[почта](@example.com)` и просто `[тут](@там)`; сочти мы такое
 * упоминанием — бек начнёт отклонять отправку сообщений, которые люди
 * писали годами. Поэтому не «что-то после собачки», а номер.
 */
const UUID_PATTERN = "[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}";

/**
 * Подпись в квадратных скобках — у упоминания и у ссылки.
 *
 * ⚠️ СКОБКА В ИМЕНИ ЭКРАНИРУЕТСЯ, КАК В MARKDOWN (`\]`). Подпись раньше была
 * «всё, кроме `]`», а имя человека скобку содержать может: упоминание
 * «Анна]» не находилось, и позванный не получал ничего — ни ошибки, ни следа
 * (найдено проверкой свойств, task-121). Одна захватывающая скобка — счёт
 * групп у разборщиков не меняется.
 */
export const LABEL_SOURCE = String.raw`((?:[^\]\\\n]|\\.)+)`;

/** Подпись → запись: `\`, `[`, `]` экранируются, перевод строки — пробел. */
export function escapeLabel(label: string): string {
  return label.replace(/[\\[\]]/gu, "\\$&").replace(/\r?\n/gu, " ");
}

/** Запись → подпись, как её видит человек. */
export function unescapeLabel(label: string): string {
  return label.replace(/\\([\\[\]])/gu, "$1");
}

/**
 * Выражение упоминания одной строкой — для тех, кто собирает свою
 * регулярку из кусков (разборщик разметки на фронте).
 *
 * Две скобки: подпись и номер. Порядок значим — на нём стоит разбор.
 */
export const MENTION_SOURCE = `\\[${LABEL_SOURCE}\\]\\(@(${UUID_PATTERN})\\)`;

/**
 * Собрать упоминание.
 *
 * Подпись — то, что человек выбрал в списке; она застывает в тексте
 * навсегда. Так же ведёт себя Телеграм: показывается то, что набрал
 * автор, а переход идёт по номеру.
 */
export function mentionMarkup(name: string, participantId: string): string {
  return `[${escapeLabel(name)}](@${participantId})`;
}

/**
 * Кого позвали в этом тексте — список номеров без повторов.
 *
 * ⚠️ РЕГУЛЯРКА СОЗДАЁТСЯ НА КАЖДЫЙ ВЫЗОВ, А НЕ ЛЕЖИТ КОНСТАНТОЙ.
 * У глобальной регулярки есть `lastIndex`, и общая на всех она помнит,
 * где остановилась в ПРОШЛЫЙ раз. Один и тот же текст дал бы то полный
 * список, то пустой — через раз, и это худший вид поломки: тест
 * зеленеет, а продукт врёт.
 *
 * Повторы схлопываются: позвать одного человека дважды в одном
 * сообщении — это один зов, а не два.
 */
export function mentionedIds(body: string): string[] {
  const rule = new RegExp(MENTION_SOURCE, "gu");
  const found = new Set<string>();
  for (const match of body.matchAll(rule)) {
    const id = match[2];
    if (id) found.add(id.toLowerCase());
  }
  return [...found];
}
