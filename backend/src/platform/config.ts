/**
 * Единственное место, где читается окружение (12-factor).
 * Всё остальное приложение получает конфиг отсюда, а не из process.env.
 */
function required(name: string): string {
  const value = process.env[name];
  if (!value) throw new Error(`Не задана переменная окружения ${name}. См. .env.example`);
  return value;
}

export const config = {
  databaseUrl: required("DATABASE_URL"),
  port: Number(process.env.API_PORT ?? 3000),
  logLevel: process.env.LOG_LEVEL ?? "info",
  isProduction: process.env.NODE_ENV === "production",
  /**
   * Можно ли держать несколько компаний на одной установке (Р-024).
   *
   * ⚠️ ПО УМОЛЧАНИЮ НЕЛЬЗЯ. Продукт — коробка: одна установка, одна
   * компания, и все, кроме первого, входят по приглашению. Разрешение
   * нужно только нашему стенду, где сотня приёмочных заводит себе
   * по компании; `compose.dev.yml` ставит его вслух, и живёт он только там.
   *
   * Настройка, которую забудут, обязана быть безопасной, — поэтому
   * «включено» требует явного слова, а не отсутствия слова.
   */
  multiWorkspace: process.env.AMPLIFIE_MULTI_WORKSPACE === "true",
  /**
   * Какая версия продукта стоит (Р-030 ⑥).
   *
   * Приезжает меткой сборки из тега git — единственного источника, который
   * невозможно забыть обновить, потому что он и есть акт выпуска. Поля
   * `version` в `package.json` нарочно НЕТ: их четыре штуки, они разъедутся,
   * и понадобится пятый гейт, стерегущий их совпадение.
   *
   * ⚠️ `null`, А НЕ ПРОЧЕРК И НЕ «dev». Установка, собранная мимо выпуска,
   * обязана говорить об этом прямо: поддержка отвечает на вопрос «что у вас
   * стоит», и выдуманное значение здесь хуже честного «не задана».
   *
   * ⚠️ `||`, А НЕ `??`, И ЭТО НЕ ПРИДИРКА. У довода сборки в Dockerfile
   * значение по умолчанию — ПУСТАЯ СТРОКА, а не отсутствие переменной.
   * `??` пропускает её насквозь, и `/health` отдал бы `""` — то есть ровно
   * тот прочерк, который запрещён строкой выше. Поймано живым прогоном.
   */
  version: process.env.AMPLIFIE_VERSION || null,
} as const;
