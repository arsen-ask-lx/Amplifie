/**
 * Хвост последних изменений в памяти процесса (task-067, Д-3).
 *
 * ЗАЧЕМ. Догон `/v1/sync` идёт в Postgres, и при живом разговоре в базу
 * идёт КАЖДАЯ открытая вкладка: замерено 101 транзакция на одну реплику,
 * когда сотня вкладок смотрит один чат. Хвост отвечает тем, кто отстал
 * недалеко, из памяти — а база остаётся источником правды и единственной
 * дорогой для отставших дальше хвоста.
 *
 * ⚠️ ЗДЕСЬ ДВЕ ДОРОГИ К ОДНИМ ДАННЫМ, И ЭТО САМЫЙ ОПАСНЫЙ ВИД КОДА.
 * Разойдясь, они разойдутся МОЛЧА и у части людей. Поэтому устройство
 * выбрано трусливое: хвост знает только то, что умеет описать точно,
 * а на всякое непонятное изменение — **забывает себя целиком** и пускает
 * всех в базу. Потеря скорости заметна замером; потерянная реплика
 * не заметна никем.
 *
 * ЧТО ЗНАЧИТ «ОПИСАТЬ ТОЧНО». Запомненная строка обязана быть той же,
 * какую отдала бы база: её отдаёт тот же `presentMessage`, которым
 * отвечает и догон. Поэтому в хвост кладутся только новые реплики —
 * у них номер изменения равен номеру самой реплики. Правка, удаление
 * и закрепление двигают номер изменения отдельно, и они хвост сбрасывают.
 *
 * ⚠️ ВИДИМОСТЬ ЕДЕТ ВМЕСТЕ СО СТРОКОЙ. Быстрая дорога не имеет права
 * стать боковым каналом к закрытому разговору, а спрашивать базу
 * «кому видно» — значит вернуть тот самый запрос, который мы убираем.
 * Поэтому адресаты считаются один раз при записи (тем же разрешителем,
 * что у шины) и хранятся рядом со строкой.
 *
 * ГДЕ ОН ЖИВЁТ. В памяти процесса, потому что процесс один. Порог назван:
 * второй узел приложения. Тогда хвост переезжает в общую память (Redis
 * или `LISTEN/NOTIFY` с чтением из базы), а этот файл остаётся местной
 * его частью — интерфейс здесь именно для этого, а не для красоты (Р-038).
 */

/** Одна запись хвоста: что изменилось, кому видно и что отдавать. */
interface Remembered<Line> {
  /** Номер изменения — тот же курсор, которым ходит `/v1/sync`. */
  seq: number;
  /** `null` — видно всем в пространстве, иначе только этим людям. */
  audience: string[] | null;
  line: Line;
}

interface State<Line> {
  /**
   * Курсор, СТРОГО БОЛЬШЕ которого хвост отвечает сам. Всё, что раньше, —
   * в базе: кольцо конечно, и старые записи из него уходят.
   */
  from: number;
  /** Последнее, что хвост знает. Он же — граница ответа. */
  head: number;
  entries: Remembered<Line>[];
}

/**
 * Сколько изменений помнить на пространство.
 *
 * Пятьсот двенадцать — не «на всякий случай», а оценка: при десяти
 * сообщениях в секунду это полминуты отставания, а дольше полуминуты
 * молчащая вкладка и так уйдёт в базу. Порог для пересмотра — замер,
 * на котором попаданий в хвост меньше 95%.
 */
const LIMIT = 512;

const byWorkspace = new Map<string, State<unknown>>();

/**
 * Запомнить изменение, которое умеем описать точно.
 *
 * Вызывать ТОЛЬКО после фиксации транзакции: запись, отменённая откатом,
 * осталась бы в памяти и уехала бы людям как настоящая.
 */
export function remember<Line>(
  workspaceId: string,
  entry: { seq: number; audience: string[] | null; line: Line },
): void {
  const state = byWorkspace.get(workspaceId) as State<Line> | undefined;
  if (!state) {
    // Первая запись после старта: хвост отвечает с этого места и ни строкой
    // раньше. Всё, что было до перезапуска, — в базе.
    byWorkspace.set(workspaceId, {
      from: entry.seq - 1,
      head: entry.seq,
      entries: [entry],
    } as State<unknown>);
    return;
  }

  // Номер пошёл не вперёд — значит наше представление о порядке неверно.
  // Не угадываем, а забываем: см. трусливое устройство выше.
  if (entry.seq <= state.head) {
    forget(workspaceId);
    return;
  }

  // Дыра: между тем, что мы помним, и этой записью что-то случилось
  // и не было описано. Отвечать из памяти больше нельзя.
  if (entry.seq !== state.head + 1) {
    forget(workspaceId);
    return;
  }

  state.entries.push(entry);
  state.head = entry.seq;
  if (state.entries.length > LIMIT) {
    const dropped = state.entries.shift();
    if (dropped) state.from = dropped.seq;
  }
}

/**
 * Забыть всё про пространство: дальше только база.
 *
 * Зовётся на КАЖДОЕ изменение, которое хвост не умеет описать точно, —
 * правку, удаление, закрепление, заводку разговора. Это не аварийный
 * путь, а обычный: правки редки, а безопасность дороже попадания.
 */
export function forget(workspaceId: string): void {
  byWorkspace.delete(workspaceId);
}

/**
 * Что изменилось после курсора и видно этому человеку — если на это можно
 * ответить из памяти.
 *
 * `null` означает «спроси базу» и говорится честно в четырёх случаях:
 * хвоста нет · курсор старше хвоста · курсор из будущего (значит наше
 * представление о порядке неверно) · записей больше, чем просили
 * страницей — разбираться со страницами должна одна дорога, и это база.
 *
 * ⚠️ ВИДИМОСТЬ ПРИМЕНЯЕТСЯ ЗДЕСЬ, А НЕ У ЗОВУЩЕГО. Забыть её на быстрой
 * дороге — значит отдать закрытую переписку тому, кто её не видит,
 * и отдать молча. Поэтому она часть ответа, а не совет.
 */
export function visibleTo<Line>(
  workspaceId: string,
  afterSeq: number,
  limit: number,
  participantId: string,
): { lines: Line[]; head: number } | null {
  const state = byWorkspace.get(workspaceId) as State<Line> | undefined;
  if (!state) return null;
  if (afterSeq < state.from) return null;
  if (afterSeq > state.head) return null;

  const fresh = state.entries.filter((one) => one.seq > afterSeq);
  if (fresh.length > limit) return null;

  const lines = fresh
    .filter((one) => one.audience === null || one.audience.includes(participantId))
    .map((one) => one.line);
  return { lines, head: state.head };
}

/** Сколько пространств помним и сколько записей — для наблюдаемости. */
export function tailSize(): { workspaces: number; entries: number } {
  let entries = 0;
  for (const state of byWorkspace.values()) entries += state.entries.length;
  return { workspaces: byWorkspace.size, entries };
}
