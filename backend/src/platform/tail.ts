/**
 * Хвост последних изменений в памяти процесса (task-067, Д-3).
 *
 * ЗАЧЕМ. Догон `/v1/sync` идёт в Postgres, и при живом разговоре в базу
 * идёт КАЖДАЯ открытая вкладка: замерено 101 транзакция на одну реплику,
 * когда сотня вкладок смотрит один чат. Хвост отвечает тем, кто отстал
 * недалеко, из памяти — а база остаётся источником правды и единственной
 * дорогой для отставших дальше хвоста.
 *
 * ⚠️ ЗДЕСЬ ДВЕ ДОРОГИ К ОДНИМ ДАННЫМ, И ЭТО САМЫЙ ОПАСНЫЙ ВИД КОДА.
 * Разойдясь, они разойдутся МОЛЧА и у части людей. Поэтому устройство
 * выбрано трусливое: хвост знает только то, что умеет описать точно,
 * а отвечает только тогда, когда может ответить ЦЕЛИКОМ. Потеря скорости
 * заметна замером; потерянная реплика не заметна никем.
 *
 * ⚠️ БОЯТЬСЯ НАДО ДЫР В ОТВЕТЕ, А НЕ ПОРЯДКА ПРИХОДА (task-084).
 * Первая редакция требовала, чтобы записи приходили строго подряд, и на
 * всякое отклонение забывала всё. Это было неверно, и вот чем: номера
 * выдаются под блокировкой, поэтому фиксация идёт по порядку — но в хвост
 * запись попадает ПОСЛЕ фиксации, а туда ещё надо успеть спросить «кому
 * видно» отдельным запросом. Две отправки меняются местами именно здесь.
 * Приходило 11 раньше 10 → сброс → следом 10 → и хвост заводился заново,
 * уверенно утверждая, что знает всё до 10, хотя реплики 11 в нём не было.
 * Вкладка получала одну строку из двух и двигала курсор: звонок про 11
 * уже прошёл, второго не будет.
 *
 * Поэтому записи живут ПО СВОЕМУ НОМЕРУ, а непрерывность проверяется
 * при ЧТЕНИИ: чтобы ответить, хвост обязан иметь все номера от «курсора
 * плюс один» до своей головы. Нет хоть одного — «спроси базу». Тогда
 * порядок прихода перестаёт значить что-либо, а дозаполненная дыра
 * возвращает быструю дорогу сама.
 *
 * ЧТО ЗНАЧИТ «ОПИСАТЬ ТОЧНО». Запомненная строка обязана быть той же,
 * какую отдала бы база: её отдаёт тот же `presentMessage`, которым
 * отвечает и догон. Поэтому в хвост кладутся только новые реплики —
 * у них номер изменения равен номеру самой реплики. Правка, удаление
 * и закрепление двигают номер изменения отдельно, и они хвост сбрасывают.
 *
 * ⚠️ ВИДИМОСТЬ ЕДЕТ ВМЕСТЕ СО СТРОКОЙ, И ЭТО СНИМОК. Быстрая дорога
 * не имеет права стать боковым каналом к закрытому разговору, а спрашивать
 * базу «кому видно» — значит вернуть тот самый запрос, который мы убираем.
 * Поэтому адресаты считаются один раз при записи (тем же разрешителем,
 * что у шины) и хранятся рядом со строкой.
 *
 * ⚠️ ОТСЮДА ИНВАРИАНТ, КОТОРЫЙ НЕЛЬЗЯ ЗАБЫТЬ: всякая запись, меняющая
 * ВИДИМОСТЬ или ЧЛЕНСТВО, обязана позвать `forget`. Снимок адресатов
 * стареет молча: появись «добавить человека в закрытый канал» — у него
 * с открытой вкладкой база отдала бы реплики по видимости «сейчас»,
 * а хвост их отфильтрует и сдвинет курсор вперёд, потеряв их навсегда.
 * Сегодня это выполняется по построению: членство заводится только при
 * создании разговора, а оно идёт через `change()`, который зовёт `forget`.
 * Машины на этот инвариант нет — держатель здесь ревью, и потому он назван
 * здесь, а не подразумевается.
 *
 * ГДЕ ОН ЖИВЁТ. В памяти процесса, потому что процесс один. Порог назван:
 * второй узел приложения. Тогда хвост переезжает в общую память (Redis
 * или `LISTEN/NOTIFY` с чтением из базы), а этот файл остаётся местной
 * его частью — интерфейс здесь именно для этого, а не для красоты (Р-038).
 */

/** Одна запись хвоста: что изменилось, кому видно и что отдавать. */
interface Remembered<Line> {
  /** Номер изменения — тот же курсор, которым ходит `/v1/sync`. */
  seq: number;
  /** `null` — видно всем в пространстве, иначе только этим людям. */
  audience: string[] | null;
  line: Line;
}

interface State<Line> {
  /**
   * Курсор, СТРОГО БОЛЬШЕ которого хвост может отвечать. Всё, что раньше, —
   * в базе: кольцо конечно, и старые записи из него уходят.
   */
  from: number;
  /** Самый большой номер, который хвост видел. Он же — граница ответа. */
  head: number;
  /** По номеру, а не по порядку прихода: порядок здесь ничего не значит. */
  entries: Map<number, Remembered<Line>>;
}

/**
 * Сколько изменений помнить на пространство.
 *
 * Пятьсот двенадцать — не «на всякий случай», а оценка: при десяти
 * сообщениях в секунду это полминуты отставания, а дольше полуминуты
 * молчащая вкладка и так уйдёт в базу. Порог для пересмотра — замер,
 * на котором попаданий в хвост меньше 95%.
 */
const LIMIT = 512;

const byWorkspace = new Map<string, State<unknown>>();

/**
 * Запомнить изменение, которое умеем описать точно.
 *
 * Вызывать ТОЛЬКО после фиксации транзакции: запись, отменённая откатом,
 * осталась бы в памяти и уехала бы людям как настоящая.
 *
 * Порядок вызовов значения не имеет — см. заголовок файла.
 */
export function remember<Line>(
  workspaceId: string,
  entry: { seq: number; audience: string[] | null; line: Line },
): void {
  const state = byWorkspace.get(workspaceId) as State<Line> | undefined;
  if (!state) {
    // Первая запись после старта: хвост отвечает с этого места и ни строкой
    // раньше. Всё, что было до перезапуска, — в базе.
    byWorkspace.set(workspaceId, {
      from: entry.seq - 1,
      head: entry.seq,
      entries: new Map([[entry.seq, entry]]),
    } as State<unknown>);
    return;
  }

  // Номер уже уехал за край кольца: ответить по нему всё равно нельзя,
  // и держать его незачем. Это не поломка — просто опоздавшая запись.
  if (entry.seq <= state.from) return;

  // Тот же номер во второй раз. Значит наше представление о порядке неверно:
  // номер выдаётся под блокировкой и дважды достаться не может. Не гадаем,
  // а забываем — единственный случай, когда это правильно.
  if (state.entries.has(entry.seq)) {
    forget(workspaceId);
    return;
  }

  state.entries.set(entry.seq, entry);
  if (entry.seq > state.head) state.head = entry.seq;
  if (state.entries.size > LIMIT) dropOldest(state);
}

/**
 * Выбросить самую старую запись и подвинуть начало.
 *
 * Ищем наименьший номер перебором от начала, а не берём первый элемент:
 * записи приходят не по порядку, и «первый добавленный» — не «самый старый».
 * Шагов столько, сколько пропущенных номеров, то есть единицы.
 */
function dropOldest<Line>(state: State<Line>): void {
  for (let seq = state.from + 1; seq <= state.head; seq++) {
    if (!state.entries.has(seq)) continue;
    state.entries.delete(seq);
    state.from = seq;
    return;
  }
}

/**
 * Забыть всё про пространство: дальше только база.
 *
 * Зовётся на КАЖДОЕ изменение, которое хвост не умеет описать точно, —
 * правку, удаление, закрепление, заводку разговора. Это не аварийный
 * путь, а обычный: правки редки, а безопасность дороже попадания.
 */
export function forget(workspaceId: string): void {
  byWorkspace.delete(workspaceId);
}

/**
 * Что изменилось после курсора и видно этому человеку — если на это можно
 * ответить из памяти.
 *
 * `null` означает «спроси базу» и говорится честно в четырёх случаях:
 * хвоста нет · курсор старше хвоста · курсор из будущего (значит наше
 * представление о порядке неверно) · записей больше, чем просили страницей
 * — разбираться со страницами должна одна дорога, и это база.
 *
 * И в пятом, ради которого всё переделано: **между курсором и головой
 * недостаёт хотя бы одного номера**. Отдать остальное значило бы сдвинуть
 * курсор человека за пропущенное, и оно не вернулось бы никогда.
 *
 * ⚠️ ВИДИМОСТЬ ПРИМЕНЯЕТСЯ ЗДЕСЬ, А НЕ У ЗОВУЩЕГО. Забыть её на быстрой
 * дороге — значит отдать закрытую переписку тому, кто её не видит,
 * и отдать молча. Поэтому она часть ответа, а не совет.
 */
export function visibleTo<Line>(
  workspaceId: string,
  afterSeq: number,
  limit: number,
  participantId: string,
): { lines: Line[]; head: number } | null {
  const state = byWorkspace.get(workspaceId) as State<Line> | undefined;
  if (!state) return null;
  if (afterSeq < state.from) return null;
  if (afterSeq > state.head) return null;
  if (state.head - afterSeq > limit) return null;

  const lines: Line[] = [];
  for (let seq = afterSeq + 1; seq <= state.head; seq++) {
    const found = state.entries.get(seq);
    // Дыра: ответить нечем, и молчать об этом нельзя.
    if (!found) return null;
    if (found.audience === null || found.audience.includes(participantId)) {
      lines.push(found.line);
    }
  }
  return { lines, head: state.head };
}

/** Сколько пространств помним и сколько записей — для наблюдаемости. */
export function tailSize(): { workspaces: number; entries: number } {
  let entries = 0;
  for (const state of byWorkspace.values()) entries += state.entries.size;
  return { workspaces: byWorkspace.size, entries };
}
