import { fileURLToPath } from "node:url";
import { drizzle } from "drizzle-orm/node-postgres";
import { migrate } from "drizzle-orm/node-postgres/migrator";
import pg from "pg";

/**
 * Накатить миграции (Р-030 ③④). Отдельная точка входа того же образа.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫМ ЗАПУСКОМ, А НЕ ВНУТРИ СТАРТА БЕКА. Это правило у нас уже
 * записано в конвейере: браузер ставится отдельным шагом, чтобы его отказ был
 * виден отказом СВОЕГО шага. Миграция внутри старта даёт клиенту бесконечный
 * перезапуск вместо диагноза — а он один на своём сервере, и разбираться
 * будет сам.
 *
 * ПОЧЕМУ НЕ `drizzle-kit`. Он оснастка разработки: в рантайм-образе его нет
 * (`npm ci --omit=dev`), и тащить его туда значило бы везти на боевой сервер
 * генератор схемы. `migrator` — часть `drizzle-orm`, то есть боевой
 * зависимости, которая там и так есть.
 */

/**
 * ⚠️ ЗАМОК БЕРЁМ МЫ САМИ, потому что у Drizzle его нет.
 *
 * `migrate()` не защищён от одновременного запуска (drizzle-orm#874): между
 * «нашёл последнюю применённую» и «применяю следующую» блокировки нет.
 * Двое разом применили бы одно и то же дважды — то есть уронили бы миграцию
 * на середине и оставили схему в неизвестном состоянии.
 *
 * Сегодня процесс у нас один и попасть в эту щель нельзя. Но опираться
 * на «нас мало» — значит опираться ровно на то, что мы сами собираемся
 * менять: Д-5 обещает второй процесс.
 *
 * Число произвольное, но постоянное: замок опознаётся по нему, и менять
 * его нельзя — иначе старая и новая версия перестанут видеть друг друга.
 */
const ЗАМОК = 4_771_030;

/**
 * Сколько ждём чужой миграции, прежде чем сдаться.
 *
 * Бесконечное ожидание неотличимо от зависшего обновления: человек видит
 * молчащий контейнер и не знает, работать ему или чинить. Пять минут —
 * заведомо больше любой нашей миграции и заведомо меньше терпения.
 */
const ЖДЁМ_ЗАМОК = "5min";

/**
 * Где лежат файлы миграций.
 *
 * Считается от собственного расположения, а не от рабочего каталога: в образе
 * запуск идёт из `/app`, а `dist/migrate.js` лежит на уровень ниже. Умолчания
 * здесь быть не должно — тот же урок, что у `make migrate`, где расхождение
 * порта приводило к молчаливому походу не туда.
 */
const МИГРАЦИИ = fileURLToPath(new URL("../migrations", import.meta.url));

/**
 * ⚠️ ОТДЕЛЬНОЕ СОЕДИНЕНИЕ, А НЕ ИЗ ПУЛА. Сеансовый `pg_advisory_lock` живёт
 * в СЕАНСЕ: взятый на соединении из пула, он вернулся бы в пул вместе
 * с замком и достался бы чужому запросу.
 *
 * ⚠️ И НЕ `pg_advisory_xact_lock`. Тот живёт до конца транзакции, а `migrate()`
 * ведёт свои транзакции сам — замок отпустило бы на первой же.
 *
 * ⚠️ АДРЕС ПРИХОДИТ ДОВОДОМ, А НЕ БЕРЁТСЯ ИЗ ОКРУЖЕНИЯ. Сперва он брался
 * из `config`, и модуль оказался непроверяемым: `config` требует
 * `DATABASE_URL` уже при загрузке, поэтому ЛЮБОЙ, кто просто импортировал
 * этот файл, обязан был иметь настроенное окружение. Приёмочная проверка
 * замка падала на импорте, не дойдя до самого замка. Функция зависит
 * от значения, а не от того, откуда оно взялось.
 */
export async function накатить(адрес: string): Promise<number> {
  const client = new pg.Client({ connectionString: адрес });
  await client.connect();

  try {
    // Применяется и к advisory-замкам: без него ожидание бесконечно.
    await client.query(`SET lock_timeout = '${ЖДЁМ_ЗАМОК}'`);
    await client.query("SELECT pg_advisory_lock($1)", [ЗАМОК]);

    try {
      const было = await применённых(client);
      await migrate(drizzle(client), { migrationsFolder: МИГРАЦИИ });
      return (await применённых(client)) - было;
    } finally {
      // Первая сеть. Вторая — сам Postgres: если процесс убит, сеанс умирает
      // и замок отпускается без нас. Две сети, потому что первая рвётся.
      await client.query("SELECT pg_advisory_unlock($1)", [ЗАМОК]);
    }
  } finally {
    await client.end();
  }
}

/** Postgres: «нет такой таблицы». На пустой базе это норма, а не поломка. */
const НЕТ_ТАБЛИЦЫ = "42P01";

/**
 * Сколько миграций уже применено.
 *
 * На совсем пустой базе журнала ещё нет — и это не отказ, а начало. Ловим
 * ровно этот код, а не любую ошибку: проглоченный отказ прав или обрыв связи
 * выглядели бы как «применено ноль» и увели бы разбор в сторону.
 */
async function применённых(client: pg.Client): Promise<number> {
  try {
    const { rows } = await client.query<{ n: string }>(
      "SELECT count(*)::text AS n FROM drizzle.__drizzle_migrations",
    );
    return Number(rows[0]?.n ?? 0);
  } catch (error) {
    if ((error as { code?: string }).code === НЕТ_ТАБЛИЦЫ) return 0;
    throw error;
  }
}

/**
 * Запуск программой. Отчёт идёт в вывод: у этой точки входа он и есть
 * интерфейс — по нему человек на своём сервере понимает, что случилось.
 */
if (process.argv[1]?.endsWith("migrate.js") || process.argv[1]?.endsWith("migrate.ts")) {
  // Окружение читается ЗДЕСЬ и только здесь: `config` — единственная дверь
  // к нему, но открывать её обязан тот, кого запустили программой, а не
  // всякий, кто взял отсюда функцию.
  const { config } = await import("./platform/config.js");
  try {
    const применено = await накатить(config.databaseUrl);
    console.log(применено > 0 ? `миграции накатаны: ${применено}` : "миграции накатывать не нужно");
    process.exit(0);
  } catch (error) {
    console.error("МИГРАЦИЯ НЕ ПРОШЛА. Приложение не запускается намеренно:");
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  }
}
