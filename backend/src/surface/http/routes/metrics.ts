import type { FastifyInstance } from "fastify";
import { render } from "../../../platform/metrics.js";

/**
 * Дверь «расскажи о себе числами» (task-087).
 *
 * ⚠️ ОНА ВНУТРЕННЯЯ, И ЭТО ДЕРЖИТСЯ НЕ ЗДЕСЬ. Caddy проксирует наружу
 * только `/v1/*` и `/health`; всё прочее уходит в статику фронта. Значит
 * `/metrics` виден лишь тому, кто уже внутри сети установки. Проверяется
 * приёмочным, а не верой: правило живёт в чужом файле, и однажды его
 * перепишут.
 *
 * Поэтому здесь нет входа по сессии — как и у `/health`. Появится
 * необходимость отдавать метрики наружу, появится и вход, но это будет
 * отдельное решение, а не молчаливое расширение этой двери.
 *
 * ⚠️ БЕЗ ЗАПРОСОВ К БАЗЕ. Опрос идёт раз в несколько секунд и не имеет
 * права быть нагрузкой; все числа берутся из памяти процесса. Стережёт
 * приёмочный по заголовку `x-db-queries`.
 */
export function registerMetricsRoutes(app: FastifyInstance): void {
  app.get("/metrics", async (_request, reply) => {
    // Формат Прометея — простой текст. `version=0.0.4` он ждёт в типе.
    reply.header("content-type", "text/plain; version=0.0.4; charset=utf-8");
    return reply.send(render());
  });
}
