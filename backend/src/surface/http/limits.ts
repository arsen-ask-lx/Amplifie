/**
 * Догон.
 *
 * ⚠️ ЭТО САМЫЙ ГОРЯЧИЙ ПУТЬ, И НИЗКИЙ ПОРОГ ЗДЕСЬ ВРЕДНЕЕ ОТСУТСТВИЯ.
 * Клиент дёргает догон на КАЖДОЕ событие в пространстве. Я поставил
 * 120 в минуту — это два события в секунду; оживлённый канал даёт больше,
 * и у того, кто просто смотрит на экран, живые обновления замолкают.
 * Поймано проверкой окна ленты: вкладка перестала видеть новые реплики
 * посреди сценария, и выглядело это как поломка ленты, а не порога.
 *
 * Десять в секунду — потолок против зациклившегося клиента, а не против
 * оживлённого разговора. Настоящий предел здесь не в частоте запросов,
 * а в том, что каждый идёт в базу (Д-3): это чинится хвостом в памяти,
 * а не порогом.
 */
export const SYNC = {
  max: 600,
  timeWindow: "1 minute",
  keyGenerator: whoRoughly,
} as const;

/**
 * Отметка прочтения.
 *
 * ⚠️ ПОРОГ ВЫШЕ, ЧЕМ У ОТПРАВКИ, И ЭТО НЕ ЩЕДРОСТЬ. Отметка идёт не от
 * рук человека, а от его ГЛАЗ: он листает ленту, и клиент шлёт её сам.
 * Клиент откладывает отправку на три секунды и шлёт пачкой (Р-029),
 * но у человека несколько каналов и две вкладки, и порог «как у
 * отправки» замолчал бы счётчик ровно тогда, когда чат оживает.
 *
 * Считаем так: 20 разговоров, две вкладки, отметка не чаще раза
 * в три секунды — 800 в минуту в худшем случае. Берём 300: до него
 * добирается только тот, кто листает все каналы разом, а такому
 * задержка счётчика не навредит.
 *
 * ⚠️ ДОРОГОВИЗНЫ ЗДЕСЬ НЕТ. Отметка — один `UPDATE` по первичному ключу
 * плюс счёт по индексу с потолком в тысячу строк. Это дешевле отправки.
 */
export const READ = {
  max: 300,
  timeWindow: "1 minute",
  keyGenerator: whoRoughly,
} as const;

