/**
 * К1–К2: отличить договорённость от болтовни.
 *
 * ЭТО ЗАГЛУШКА, И ОНА НАЗВАНА ЗАГЛУШКОЙ. Здесь простые правила, а не
 * модель: ключа к модели нет, бюджет не назначен (О-1, О-2), и решать
 * это за владельца нельзя.
 *
 * ЗАЧЕМ ТОГДА ОНА. Во-первых, петля К1→К5 замыкается уже сейчас и её
 * можно потрогать. Во-вторых — и это важнее — она даёт **опорное число**:
 * насколько далеко уезжает модель от дешёвых правил. Без опоры любая
 * цифра модели выглядит хорошей.
 *
 * ГДЕ ОНА ЖИВЁТ. В `agent/`, снаружи ядра: этот слой выбрасывается целиком.
 * Придёт модель — заменится ровно этот файл, а ядро не заметит.
 *
 * ⚠️ ГРАНИЦА СЛОВА. Здесь НЕ используется `\b`: в JavaScript он считает
 * буквами только латиницу, и `\bя` не работает вовсе. Первая редакция
 * этого файла молчала на всех обещаниях именно поэтому. Границы заданы
 * явными просмотрами по списку букв.
 */

export interface Heard {
  /** Сообщение, из которого следует обязательство. */
  messageId: string;
  /** Дословная цитата — то, на чём основано утверждение. */
  quote: string;
  /** Текст договорённости своими словами. */
  text: string;
}

export interface Said {
  id: string;
  body: string;
  authorName: string;
  kind: string;
}

/** Буква — кириллица и латиница. Границы слов строятся отсюда. */
const LETTER = "[а-яёa-z]";
const START = `(?<!${LETTER})`;
const END = `(?!${LETTER})`;

const rule = (body: string) => new RegExp(`${START}(?:${body})${END}`, "iu");

/**
 * Начало предложения или части: там первое лицо стоит без «я».
 * «Подготовлю смету», «Да, посмотрю сегодня».
 */
const CLAUSE_START = "(?:^|[.!?,:;—–-]\\s*)";

/** Глагол первого лица будущего времени: «пришлю», «согласую». */
const FIRST_PERSON_VERB = "[а-яё]{3,}(?:ю|у)";

/** «я пришлю» либо «Пришлю» в начале части предложения. */
const PROMISES = [
  new RegExp(`${START}я\\s+${FIRST_PERSON_VERB}${END}`, "iu"),
  new RegExp(`${CLAUSE_START}${FIRST_PERSON_VERB}${END}`, "iu"),
];

/** Обязательство сказано прямо — срок при этом не обязателен. */
const TAKES_IT_ON = [rule("беру\\s+на\\s+себя"), rule("договорились")];

/** Срок: «к четвергу», «сегодня», «до конца недели», «на среду». */
/**
 * ОСНОВЫ, а не полные формы. Русский падеж съедает окончание: «к пятнице»,
 * «в среду», «до понедельника» — и список полных форм пропускал их
 * молча. Окончание добирается `[а-яё]*` ниже.
 */
const DAYS = "понедельник|вторник|сред|четверг|пятниц|суббот|воскресень|пн|вт|ср|чт|пт|сб|вс";
const WHEN = rule(
  [
    "сегодня|завтра|послезавтра|утром|вечером|ночью",
    "в\\s+выходные",
    `(?:в|на|к|до)\\s+(?:${DAYS})[а-яё]*`,
    "к\\s+[а-яё]+у",
    "до\\s+конца\\s+[а-яё]+",
    "на\\s+(?:этой|следующей)\\s+неделе",
  ].join("|"),
);

/**
 * Слова, при которых обязательства нет, даже если форма похожа.
 *
 * Список собран по корпусу арбитра, а не выдуман: каждая строка — это
 * реплика, на которой правила иначе ошибались.
 */
const NOT_A_PROMISE = [
  rule("надо\\s+бы"),
  rule("можно\\s+было\\s+бы"),
  rule("наверное"),
  rule("кажется"),
  rule("думаю"),
  rule("могу"),
  rule("стоит\\s+проверить"),
  rule("уже\\s+не\\s+надо"),
  rule("отменя[а-яё]*"),
  rule("не\\s+получится"),
  rule("передумал[а-яё]*"),
  rule("если\\s+(?:будет\\s+)?врем[а-яё]*"),
];

function looksLikePromise(body: string): boolean {
  if (NOT_A_PROMISE.some((no) => no.test(body))) return false;
  if (TAKES_IT_ON.some((yes) => yes.test(body))) return true;

  // Первое лицо без срока — это ещё не обязательство: «я думаю»,
  // «я посмотрю как-нибудь». Срок и есть то, что делает его проверяемым.
  return PROMISES.some((yes) => yes.test(body)) && WHEN.test(body);
}

/** Договорённость своими словами: пока — очищенная реплика с автором. */
function phrase(said: Said): string {
  const cleaned = said.body.replace(/\s+/gu, " ").trim();
  const short = cleaned.length > 200 ? `${cleaned.slice(0, 197)}…` : cleaned;
  return `${said.authorName}: ${short}`;
}

/**
 * Что услышано в разговоре.
 *
 * Сообщения агента пропускаются: саммари, положенное в канал, вернулось бы
 * ему же на вход и породило договорённость из собственных слов.
 *
 * ЧЕГО ЭТИ ПРАВИЛА ЗАВЕДОМО НЕ УМЕЮТ (проверено на корпусе):
 * условное обязательство («возьму, если Петя закроет»), отмену ранее
 * сказанного в отдельной реплике, иронию («перепишу за одну ночь, ага»),
 * принятие односложным «угу». Это не оправдание, а спецификация того,
 * что обязана уметь модель.
 */
export function hear(messages: Said[]): Heard[] {
  return messages
    .filter((said) => said.kind === "human" && looksLikePromise(said.body))
    .map((said) => ({
      messageId: said.id,
      quote: said.body,
      text: phrase(said),
    }));
}
