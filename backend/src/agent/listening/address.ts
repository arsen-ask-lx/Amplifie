import { mentionedIds } from "@amplifie/contract";

/**
 * Обращение к агенту: `@memo` в тексте сообщения.
 *
 * ЗАЧЕМ ОТДЕЛЬНО ОТ `detect.ts`. Там К1–К2: «есть ли здесь договорённость».
 * Здесь другой вопрос: «звали ли меня». Второй решается за микросекунды
 * и обязан решаться ДО первого — иначе модель зовётся на каждое сообщение
 * каждого канала, и это разоряет. Тот же порядок у Buzz: дешёвое
 * детерминированное выражение, и только на остатке — модель.
 *
 * ⚠️ ГРАНИЦА СЛОВА. Здесь НЕ используется `\b`: в JavaScript он считает
 * буквами только латиницу, и `\bСводка` не работает — а по-русски зовут
 * людей, и скоро будут звать (task-033). Первая редакция
 * `detect.ts` молчала на всех обещаниях именно поэтому. Границы заданы
 * явным просмотром по списку букв — тот же приём, что и там.
 *
 * ⚠️ ЧТО НЕ ОБРАЩЕНИЕ. `@memory` — другое слово; `@Сводкой`, `@Сводкам` —
 * падежи русского имени не считаются.
 * Это осознанно узко: имя участника пишется как есть, а угадывание
 * склонений даёт ложные срабатывания, каждое из которых стоит денег.
 */

/** Буква — кириллица и латиница, плюс цифры и дефис внутри имени. */
const NAME_CHAR = "[а-яёa-z0-9_-]";

/** Экранирование для подстановки имени в выражение. */
function quoted(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/gu, "\\$&");
}

/**
 * Звали ли агента в этом тексте.
 *
 * Регистр не важен: `@memo` и `@MEMO` — одно и то же обращение.
 *
 * ⚠️ ЭТО ОДНО ИЗ ДВУХ НАПИСАНИЙ ОБРАЩЕНИЯ. Второе — узел упоминания
 * с номером участника (Р-031), и его читает `addressedById`. Два
 * написания, а обращение одно: человек не должен догадываться, каким
 * способом позвать, чтобы его услышали.
 */
export function addressedTo(body: string, agentName: string): boolean {
  const name = agentName.trim();
  if (!name) return false;

  // (?<!…) слева: `почта@memo` — не обращение, а часть адреса.
  // (?!…) справа: `@memory` — другое слово.
  const rule = new RegExp(`(?<!${NAME_CHAR})@${quoted(name)}(?!${NAME_CHAR})`, "iu");
  return rule.test(body);
}

/**
 * Позвали ли агента упоминанием — узлом с его номером (Р-031).
 *
 * ⚠️ БЕЗ ЭТОГО АГЕНТ ЗАМОЛКАЕТ, И ЗАМОЛКАЕТ МОЛЧА. Как только поле ввода
 * начинает превращать выбранное из списка в узел упоминания, текст
 * перестаёт содержать простое `@memo` — и поиск по тексту перестаёт
 * находить обращение. Человек видит в своей реплике имя агента и ждёт
 * ответа, которого не будет.
 */
export function addressedById(body: string, agentParticipantId: string): boolean {
  if (!agentParticipantId) return false;
  return mentionedIds(body).includes(agentParticipantId.toLowerCase());
}

/** Реплика в том виде, в каком её видит распознавание. */
export interface Line {
  body: string;
  authorKind: string;
}

/**
 * Ждёт ли разговор ответа агента.
 *
 * Отвечает только на ПОСЛЕДНЕЕ слово в ленте, и только если это слово
 * сказал человек. Иначе выходит петля: агент пишет `@memo, и тебе
 * привет`, следующий разбор видит обращение и зовёт его снова — и так
 * до конца тарифа. Тот же гейт `ignore_self` у Buzz.
 *
 * ⚠️ ЛЕНТА В ПОРЯДКЕ ЧТЕНИЯ: старое первым, свежее последним. Именно так
 * её отдаёт `listMessages` — хранилище выбирает по убыванию номера и
 * разворачивает (`rows.reverse()`). Первая редакция этого файла считала
 * наоборот и молчала на любом разговоре длиннее одной реплики; быстрые
 * тесты этого не поймали, потому что кодировали то же неверное допущение.
 */
export function awaitsAnswer(
  feed: readonly Line[],
  agentName: string,
  agentParticipantId = "",
): boolean {
  const last = feed.at(-1);
  if (!last) return false;
  if (last.authorKind === "agent") return false;
  return addressedTo(last.body, agentName) || addressedById(last.body, agentParticipantId);
}
