/**
 * Проверки распознавания договорённостей.
 *
 * Примеры взяты из корпуса арбитра (arbiter/corpus.jsonl) — того самого,
 * на котором меряется главная ставка продукта. Здесь не выдуманные фразы,
 * а те, по которым потом будет считаться каппа.
 *
 * Раздел «чего заведомо не умеет» — не позор, а спецификация: он
 * перечисляет то, ради чего понадобится модель.
 */
import { describe, expect, it } from "vitest";
import { hear, type Said } from "./detect.js";

const human = (body: string, id = "m1"): Said => ({
  id,
  body,
  authorName: "Пётр",
  kind: "human",
});

const heardIn = (body: string) => hear([human(body)]);

describe("слышит обязательство", () => {
  it.each([
    "Хорошо, я выгружу их к четвергу.",
    "Я заберу, к четвергу пришлю сводку.",
    "Беру на себя, наберу их завтра утром.",
    "Подготовлю смету и отправлю ему в понедельник.",
    "Согласую до конца недели.",
    "Напишу черновик к понедельнику, дальше поправите.",
    "Разошлю письмо сегодня, шаблон уже есть.",
    "Перенесу на среду, всем разошлю приглашение.",
    "Да, посмотрю сегодня вечером.",
    "Договорились: берём тот, что дешевле, я оформлю оплату.",
  ])("%s", (body) => {
    expect(heardIn(body)).toHaveLength(1);
  });

  it("цитата дословная, а не пересказ", () => {
    const body = "Я подготовлю отчёт к пятнице.";
    expect(heardIn(body)[0]?.quote).toBe(body);
  });

  it("в тексте договорённости назван автор", () => {
    expect(heardIn("Я подготовлю отчёт к пятнице.")[0]?.text).toContain("Пётр");
  });
});

describe("не слышит болтовню", () => {
  it.each([
    "Отлично, ездили за город.",
    "Да, раздражает страшно.",
    "Третий раз за месяц.",
    "Согласен, читается легко.",
    "Сорок два.",
    "Доброе!",
    "Оно и видно.",
    "Надо бы кеш прикрутить.",
    "Можно было бы поставить отдельный сервис, но это дорого.",
    "Наверное когда-нибудь понадобится.",
    "Думаю, отдельная таблица подойдёт.",
    "Скорее всего из-за картинок. Стоит проверить.",
    "Могу глянуть, если время будет.",
    "Уже не надо, разобрались.",
    "Отменяется, миграцию пока откладываем.",
    "Слушай, не получится, у меня командировка.",
    "Передумал, оставляем как есть.",
  ])("%s", (body) => {
    expect(heardIn(body)).toHaveLength(0);
  });

  it("прошедшее время — отчёт, а не обязательство", () => {
    expect(heardIn("Выгрузил вчера, всё на месте.")).toHaveLength(0);
    expect(heardIn("Обновил утром.")).toHaveLength(0);
  });
});

describe("границы, названные вслух", () => {
  it("сообщение агента не слушаем — иначе он услышит сам себя", () => {
    const own: Said = {
      id: "a1",
      body: "Я пришлю сводку к четвергу.",
      authorName: "memo",
      kind: "agent",
    };
    expect(hear([own])).toHaveLength(0);
  });

  it("каждое обязательство — отдельная договорённость", () => {
    const said = [
      human("Я пришлю смету в понедельник.", "m1"),
      human("Как выходные?", "m2"),
      human("Согласую договор до пятницы.", "m3"),
    ];
    expect(hear(said).map((h) => h.messageId)).toEqual(["m1", "m3"]);
  });
});
