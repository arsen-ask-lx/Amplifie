/**
 * Сборка подсказки из ленты разговора.
 *
 * ПОЧЕМУ ОБРЕЗКА ПО ОБЪЁМУ, А НЕ ПО ЧИСЛУ РЕПЛИК. Одна реплика бывает
 * длиннее сотни: кто-то вставил лог. Обрезка по счёту даёт непредсказуемый
 * размер подсказки, а значит непредсказуемую цену вызова и непредсказуемый
 * отказ модели по длине контекста. Считаем знаки.
 *
 * ⚠️ ЛЕНТА ПРИХОДИТ В ПОРЯДКЕ ЧТЕНИЯ: старое первым, вопрос последним —
 * так её отдаёт `listMessages`. Набирать бюджет надо С КОНЦА: если резать
 * с начала, первым потеряется самое свежее, то есть сам вопрос. Порядок
 * на выходе сохраняется читаемым.
 *
 * ⚠️ ТЕКСТ ЛЕНТЫ — ЭТО РЕЧЬ ЛЮДЕЙ, А НЕ КОМАНДЫ. Он идёт в подсказку как
 * данные. Разделитель между строками выбран так, чтобы реплика не могла
 * притвориться служебной разметкой: имя автора и вид ставит сервер,
 * а не текст сообщения.
 */

/** Реплика в том виде, в каком её видит сборка. */
export interface Turn {
  body: string;
  authorName: string;
  authorKind: string;
  /**
   * В каком чате сказано. Ставится, только когда область чтения шире
   * одного чата (Р-032): иначе строка «Смета · Мария: …» повторяла бы
   * название канала в каждой строке и съедала бюджет ни за чем.
   */
  where?: string;
}

/**
 * Сколько знаков ленты уходит в подсказку.
 *
 * Число грубое и намеренно: точная граница зависит от модели и тарифа,
 * а О-1 (лимит токенов) владельцем пока не назван. Двенадцать тысяч
 * знаков — это примерно три-четыре тысячи токенов, безопасно для любой
 * из моделей, которые мы поддерживаем.
 */
const BUDGET = 12_000;

