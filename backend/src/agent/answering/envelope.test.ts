/**
 * Быстрые проверки разбора конверта с действиями (Р-017).
 *
 * Написаны ДО кода. Здесь проверяется главное правило рубежа команд:
 * **непонятый ответ никогда не превращается в действие.** Всё остальное —
 * ступени восстановления, ради которых этот разбор и существует: модели
 * оборачивают JSON в тройные кавычки вопреки запрету, и терять из-за
 * этого действие обидно, а догадываться — опасно.
 */
import { describe, expect, it } from "vitest";
import { LIMIT, readEnvelope } from "./envelope.js";

const plain = (text: string) => ({ text, actions: [] });

describe("разбор конверта", () => {
  it("обычный конверт разбирается", () => {
    const raw = JSON.stringify({
      ответ: "Завёл.",
      действия: [{ вид: "создать-задачу", текст: "Выгрузка логов" }],
    });
    expect(readEnvelope(raw)).toEqual({
      text: "Завёл.",
      actions: [{ kind: "создать-задачу", text: "Выгрузка логов" }],
    });
  });

  it("обёртка в тройные кавычки снимается", () => {
    // Самая частая поломка структурированного вывода: модель оборачивает
    // ответ в ```json даже когда просили без обёртки.
    const raw = '```json\n{"ответ":"Готово","действия":[]}\n```';
    expect(readEnvelope(raw)).toEqual(plain("Готово"));
  });

  it("конверт среди болтовни вырезается по скобкам", () => {
    const raw = 'Вот мой ответ: {"ответ":"Ага","действия":[]} — надеюсь, помог.';
    expect(readEnvelope(raw)).toEqual(plain("Ага"));
  });

  it("мусор становится простым ответом, а не ошибкой", () => {
    // Правило Р-017: не понял — значит действий нет. Не падение,
    // не догадка, а честный простой ответ.
    const raw = "Просто текст без всякого конверта.";
    expect(readEnvelope(raw)).toEqual(plain("Просто текст без всякого конверта."));
  });

  it("полу-JSON становится простым ответом", () => {
    const raw = '{"ответ":"оборвался посередине';
    expect(readEnvelope(raw)).toEqual(plain(raw));
  });

  it("конверт без поля ответа считается простым ответом", () => {
    // Схема не сошлась — значит это не конверт, что бы там ни было.
    const raw = '{"действия":[{"вид":"создать-задачу","текст":"тайком"}]}';
    expect(readEnvelope(raw).actions).toHaveLength(0);
  });

  it("неизвестный вид действия отбрасывается, остальные остаются", () => {
    const raw = JSON.stringify({
      ответ: "Сделал часть.",
      действия: [
        { вид: "удалить-канал", текст: "Инфраструктура" },
        { вид: "создать-задачу", текст: "Живое" },
        { вид: "выполнить", текст: "rm -rf /" },
      ],
    });
    const read = readEnvelope(raw);
    expect(read.actions).toEqual([{ kind: "создать-задачу", text: "Живое" }]);
  });

  it("поток действий обрезается по пределу", () => {
    const many = Array.from({ length: 20 }, (_, i) => ({
      вид: "создать-задачу",
      текст: `Задача ${i}`,
    }));
    const read = readEnvelope(JSON.stringify({ ответ: "Много", действия: many }));
    expect(read.actions).toHaveLength(LIMIT);
    expect(read.actions[0]?.text).toBe("Задача 0");
  });

  it("действие с пустым текстом не считается действием", () => {
    const raw = JSON.stringify({
      ответ: "Пусто",
      действия: [{ вид: "создать-задачу", текст: "   " }],
    });
    expect(readEnvelope(raw).actions).toHaveLength(0);
  });

  it("слишком длинный текст действия обрезается, а не отбрасывается", () => {
    // Название задачи в двести тысяч знаков — это не злой умысел,
    // а болтливая модель. Обрезаем, но действие сохраняем.
    const raw = JSON.stringify({
      ответ: "Длинно",
      действия: [{ вид: "создать-задачу", текст: "я".repeat(5000) }],
    });
    const read = readEnvelope(raw);
    expect(read.actions).toHaveLength(1);
    expect(read.actions[0]?.text.length).toBeLessThanOrEqual(200);
  });
});
