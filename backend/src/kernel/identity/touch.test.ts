import { describe, expect, it } from "vitest";
import { staleTouch } from "./repo.js";

/**
 * ТОЧЕЧНЫЕ ПРОВЕРКИ ПРАВИЛА «ПОРА ЛИ ОТМЕЧАТЬ СЕССИЮ ЖИВОЙ» (task-083).
 *
 * ⚠️ ЗДЕСЬ ТОЧЕЧНЫЕ, А НЕ ПРИЁМОЧНЫЕ, И ЭТО ОБОСНОВАНО. Снаружи отметка
 * не видна ни одной дверью — она про эксплуатацию, а не про продукт.
 * Зато само правило — граница со сроком, и ошибиться в нём можно двумя
 * способами: отмечать всегда (возвращается лишний запрос к базе на каждое
 * обращение, ради чего работа и делалась) или не отмечать никогда (поле
 * тихо перестаёт означать хоть что-то). Оба случая молчаливы.
 *
 * Что отметка действительно ставится, проверено живым прогоном: у сессии,
 * сделавшей первый запрос, `last_seen_at` перестаёт быть пустым (журнал
 * task-083).
 */

const MINUTE = 60 * 1000;
const now = new Date("2026-09-16T12:00:00.000Z");

describe("пора ли отмечать сессию живой", () => {
  it("никогда не отмечалась — значит пора", () => {
    // Пустое поле у только что заведённой сессии: без этой ветки отметка
    // не появилась бы никогда, а срок считался бы от несуществующего.
    expect(staleTouch(null, now)).toBe(true);
  });

  it("отмечена только что — не трогаем", () => {
    expect(staleTouch(new Date(now.getTime() - MINUTE), now)).toBe(false);
  });

  it("отмечена давно — пора", () => {
    expect(staleTouch(new Date(now.getTime() - 6 * MINUTE), now)).toBe(true);
  });

  it("ровно на пороге — ещё не пора", () => {
    // Граница закрыта в сторону «не писать»: лишний запрос к базе дороже
    // пятиминутной неточности поля, которое никто не читает чаще.
    expect(staleTouch(new Date(now.getTime() - 5 * MINUTE), now)).toBe(false);
  });
});
