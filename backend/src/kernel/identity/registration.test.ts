import { describe, expect, it } from "vitest";
import { mayRegister } from "./registration.js";

/**
 * ПРОВЕРКА ПРАВИЛА «ОДНА УСТАНОВКА — ОДНА КОМПАНИЯ» (Р-024, task-017 §5).
 *
 * ⚠️ ПОЧЕМУ ЭТО ЧИСТАЯ ФУНКЦИЯ, А НЕ ПРИЁМОЧНАЯ. Закрытая регистрация
 * не проверяется по живому стеку: наш стенд поднят с разрешением на много
 * компаний — иначе 111 приёмочных не смогли бы завести себе по компании.
 * То есть ветку «закрыто» на стенде не увидеть в принципе. Правило вынесено
 * сюда, чтобы у него был хоть какой-то арбитр, и это названо честно:
 * приёмочной на закрытую дверь у нас нет.
 */
describe("одна установка — одна компания", () => {
  it("первый человек регистрируется всегда", () => {
    expect(mayRegister({ workspacesExist: false, multiWorkspace: false })).toBe(true);
  });

  it("второй — уже нет: дверь одна, и это приглашение", () => {
    // ⚠️ ЭТО НЕ УДОБСТВО, А ДЫРА. Коллега, которому дали адрес сервера,
    // заводил на ЧУЖОМ железе свою отдельную компанию: владелец её
    // не видит, она не видит владельца, а место занимает.
    expect(mayRegister({ workspacesExist: true, multiWorkspace: false })).toBe(false);
  });

  it("с разрешением на много компаний — можно, и это только для стенда", () => {
    expect(mayRegister({ workspacesExist: true, multiWorkspace: true })).toBe(true);
  });
});
