/**
 * Кому вообще можно регистрироваться (Р-024).
 *
 * ⚠️ ОДНА УСТАНОВКА — ОДНА КОМПАНИЯ, И ЭТО НЕ ОГРАНИЧЕНИЕ, А ЗАКРЫТАЯ
 * ДЫРА. Пока регистрация была открыта, коллега, которому дали адрес
 * сервера, заводил на ЧУЖОМ железе СВОЮ отдельную компанию: владелец её
 * не видит, она не видит владельца, но живёт и занимает место. Это
 * не задумка была, а недоделка.
 *
 * Первый человек регистрируется всегда — он и есть компания. Все
 * остальные входят одной дверью: по приглашению (Р-009).
 *
 * ⚠️ РАЗРЕШЕНИЕ НА МНОГО КОМПАНИЙ — ТОЛЬКО ДЛЯ СТЕНДА. Наши приёмочные
 * заводят себе по компании на тест: сотня тестов — сотня компаний, иначе
 * они мешали бы друг другу в одной. Поэтому `compose.yml` этого стенда
 * ставит `AMPLIFIE_MULTI_WORKSPACE=true` вслух и с оговоркой, а значение
 * по умолчанию — «нельзя»: та настройка, которую забудут, обязана быть
 * безопасной.
 */
export function mayRegister(input: {
  /** Есть ли на этой установке хоть одна компания. */
  workspacesExist: boolean;
  /** Разрешено ли держать их несколько. */
  multiWorkspace: boolean;
}): boolean {
  return !input.workspacesExist || input.multiWorkspace;
}
