import { type SQL, sql } from "drizzle-orm";

/**
 * Как слова поиска становятся запросом Postgres (task-100).
 *
 * ⚠️ ОТДЕЛЬНО ОТ СЛУЖБЫ ПОИСКА И БЕЗ БАЗЫ. Это чистое правило: на вход —
 * слова, на выход — выражение. Слова разбирает общий пакет (`searchWords`),
 * потому что по ним же подсвечивает клиент.
 */

/**
 * Слова → выражение: каждое слово — по началу (`simple`) ИЛИ по основе
 * (`russian`), слова — через «и». Стоп-слово даёт пустую русскую часть
 * и ищется началом слова: «не пришёл» находит «не пришёл». Слова едут
 * параметрами, а не текстом запроса.
 */
export function tsqueryOf(words: string[]): SQL {
  return sql.join(
    words.map(
      (word) => sql`(to_tsquery('simple', ${`${word}:*`}) || to_tsquery('russian', ${word}))`,
    ),
    sql` && `,
  );
}
