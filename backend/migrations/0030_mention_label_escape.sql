-- Подпись упоминания экранируется как в markdown (task-121): `\]`, `\[`, `\\`.
--
-- Имя человека может содержать `]`, а подпись была «всё, кроме `]`»: упоминание
-- «Анна]» не находилось, и позванный не получал ничего (найдено проверкой
-- свойств). Правило в `packages/contract/src/mentions.ts` сменилось, и функция
-- индекса поиска обязана вычищать упоминание тем же выражением.
--
-- ⚠️ ЗАМЕНА ФУНКЦИИ, А НЕ ПЕРЕСТРОЙКА ИНДЕКСА. Новое выражение читает старые
-- записи так же, как прежнее: подписей с обратной чертой перед `]` раньше не
-- было, подпись со скобкой не была упоминанием вовсе. Готовые строки
-- `message_search` верны и без пересчёта; замок — только каталога, мгновенно.
-- Откат образа на прошлую версию безопасен: старый код пишет подпись без
-- экранирования, а её новое выражение читает по-старому.
--
-- Обратная черта в тексте индекса не раскрывается: для `to_tsvector` это
-- знак препинания, слова подписи находятся и так.
-- ⚠️ ВЫРАЖЕНИЕ ОБЯЗАНО СОВПАДАТЬ С `MENTION_SOURCE` — стережёт `talk/search.test.ts`.
CREATE OR REPLACE FUNCTION search_text(body text) RETURNS text
  LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
  SELECT regexp_replace(
    body,
    '\[((?:[^\]\\\n]|\\.)+)\]\(@([0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12})\)',
    '\1',
    'g'
  )
$$;
