-- Восстановление инварианта «погашено — это ДВА поля разом».
--
-- ЧТО ПРОИЗОШЛО. Погашение было написано в два запроса: сначала атомарный
-- захват, потом простановка того, кем погашено. Между ними строка нарушала
-- пару, и проверка это ловила. Попытка отложить проверку до фиксации
-- провалилась: **Postgres не умеет DEFERRABLE для CHECK** — откладывать
-- можно уникальность, внешние ключи и исключения, но не проверку значений.
--
-- ЧТО СДЕЛАНО ВМЕСТО. Инвариант оставлен немедленным, а исправлен КОД:
-- оба поля теперь ставятся одним UPDATE. Это и честнее — «погашено кем-то»
-- перестало быть представимым состоянием даже на миг.
--
-- Запись нужна потому, что констрейнт успел уйти из базы, пока это
-- выяснялось. Здесь он возвращается.
