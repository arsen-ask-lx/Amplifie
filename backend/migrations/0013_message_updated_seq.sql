-- chat-edit-delete-sync: у реплики появляется второй номер.
--
-- ⚠️ ДВА НОМЕРА ОТВЕЧАЮТ НА РАЗНЫЕ ВОПРОСЫ, И ИМЕННО ПОЭТОМУ ИХ ДВА.
-- `seq` — «когда это было сказано»: по нему реплика стоит в разговоре.
-- `updated_seq` — «когда это в последний раз менялось»: по нему реплика
-- попадает в догон. Одним числом обслужить оба вопроса нельзя: правка
-- старой реплики либо не доедет до чужой вкладки (сегодня), либо уедет
-- в конец ленты (если двигать сам `seq`).
--
-- Оба номера берутся из ОДНОГО счётчика пространства (`workspace.last_seq`),
-- поэтому у клиента остаётся один курсор. Два счётчика означали бы пару
-- курсоров и вопрос «что делать, когда они разошлись».
--
-- Так же устроен Телеграм: `pts` растёт и на отправке, и на правке,
-- и на удалении, а `getDifference` догоняет по нему.

-- ⚠️ ЗАПОЛНЯЕМ СТАРЫЕ СТРОКИ ЗНАЧЕНИЕМ `seq`, А НЕ НУЛЁМ И НЕ «СЕЙЧАС».
-- Клиент, который уже догнал до курсора N, не должен получить всю историю
-- заново: при `updated_seq = seq` все старые реплики остаются позади его
-- курсора, и для него не меняется ничего.
ALTER TABLE "message" ADD COLUMN IF NOT EXISTS "updated_seq" bigint;
UPDATE "message" SET "updated_seq" = "seq" WHERE "updated_seq" IS NULL;
ALTER TABLE "message" ALTER COLUMN "updated_seq" SET NOT NULL;

-- Догон отбирает по пространству и номеру изменения — тем же порядком
-- полей, что и в индексе. Ключ арендатора первым (Р-7).
CREATE INDEX IF NOT EXISTS "message_workspace_updated_seq_idx"
  ON "message" ("workspace_id", "updated_seq");
