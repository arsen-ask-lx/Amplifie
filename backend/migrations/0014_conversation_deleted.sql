-- Удаление канала.
--
-- ⚠️ МЯГКО, ТОЙ ЖЕ ПРИЧИНОЙ, ЧТО И У РЕПЛИКИ. Жёсткое удаление унесло бы
-- каскадом все сообщения канала — а на них ссылаются ответы и пересылки
-- из ДРУГИХ каналов, и те превратились бы в цитаты в пустоту. Плюс
-- о жёстком удалении нечем рассказать чужой вкладке: исчезнувшей строки
-- в догоне нет.
--
-- Строка остаётся; из списка канал уходит отбором, а не забвением.
ALTER TABLE "conversation" ADD COLUMN IF NOT EXISTS "deleted_at" timestamptz;

-- Частичный индекс: удалённых каналов единицы, а условие «не удалён»
-- стоит в каждом запросе списка. Полный индекс по почти пустому столбцу
-- был бы платой без выгоды.
CREATE INDEX IF NOT EXISTS "conversation_workspace_alive_idx"
  ON "conversation" ("workspace_id") WHERE "deleted_at" IS NULL;
