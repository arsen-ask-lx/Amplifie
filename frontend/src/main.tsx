import { IconContext } from "@phosphor-icons/react";
import { StrictMode } from "react";
import { createRoot } from "react-dom/client";
import { BrowserRouter } from "react-router";
import { App } from "./app/App.js";
import { Toasts } from "./shared/toast.js";
import { TooltipProvider } from "./shared/ui/tooltip.js";
// Geist — свой, а не с чужого домена. Пакет кладёт .woff2 рядом, сборщик
// вшивает их в статику: ни одного обращения наружу при открытии
// приложения. Подмножество с кириллицей в пакете есть — без него
// интерфейс на русском грузил бы шрифт и не мог им воспользоваться.
import "@fontsource-variable/geist";
// Unbounded — ТОЛЬКО имя продукта, одно слово в двух местах. Отдельная
// гарнитура ради одного слова оправдана ровно тем, ради чего у продукта
// вообще бывает лицо: узнаваемостью. В текст она не пойдёт никогда —
// плакатный шрифт в переписке нечитаем, и это записано в роли ниже.
// Кириллица в пакете есть: имя латинское, но роль может пригодиться
// заголовку, и подмножество без кириллицы завело бы нас в тупик молча.
import "@fontsource-variable/unbounded";
import "./styles.css";
import { apply, chosen } from "./shared/theme.js";

// ДО отрисовки: иначе тот, кто сидит в тёмной, увидит белый первый кадр.
apply(chosen());

// ⚠️ «ТЫКАЛКА» БОЛЬШЕ НЕ ЗАПУСКАЕТСЯ ОТСЮДА, И ЭТО НЕ ЗАБЫВЧИВОСТЬ.
// Она переехала в пакет `agent-ui-kit`, который подключает сам сборщик
// (см. `vite.config.ts`). Двух её быть не может: пока запускались обе,
// на Alt+щелчок открывалось ДВА поля друг на друге — фокус доставался
// одному, буквы уходили в другое, и написать было нельзя ни в одно.
// Владелец это и поймал; воспроизведено прогоном.

const root = document.getElementById("root");
if (!root) throw new Error("нет узла #root");

createRoot(root).render(
  <StrictMode>
    <BrowserRouter>
      {/* Один поставщик подсказок на всё приложение: он держит общую
          задержку и следит, чтобы две подсказки не висели разом. */}
      {/* ⚠️ НАЧЕРТАНИЕ ЗНАЧКОВ ОБЪЯВЛЕНО ОДИН РАЗ И ЗДЕСЬ. У Phosphor их
          шесть — тонкое, лёгкое, обычное, жирное, залитое, дуотон, — и это
          ровно та причина, по которой набор выбран. Но выбор начертания
          в каждом месте по отдельности означал бы, что интерфейс собран
          из значков разной толщины: такое видно сразу и не чинится.
          `regular` — рабочее; заливка ставится по месту там, где значок
          обозначает включённое состояние. */}
      <IconContext.Provider value={{ weight: "regular" }}>
        <TooltipProvider delayDuration={300}>
          <App />
          {/* ⚠️ ПЛАШКА ОБЪЯВЛЕНА ОДИН РАЗ И ЗДЕСЬ, как и начертание значков
              выше. Она стоит по центру ОКНА — так у Телеграма, где
              родителем плашки служит окно целиком, а не лента (Р-028).
              Вторая такая же в глубине экрана дала бы два центра. */}
          <Toasts />
        </TooltipProvider>
      </IconContext.Provider>
    </BrowserRouter>
  </StrictMode>,
);
