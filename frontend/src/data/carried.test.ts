import { describe, expect, it } from "vitest";
import { carried } from "./carried.js";

/**
 * ТОЧЕЧНЫЕ ПРОВЕРКИ ПРАВИЛА «ЧТО ДЕЛАТЬ С ПРИЕХАВШЕЙ РЕПЛИКОЙ» (task-085,
 * П-4 и П-5).
 *
 * ⚠️ ЗДЕСЬ ТОЧЕЧНЫЕ, А НЕ СЦЕНАРИЙ БРАУЗЕРА, И ЭТО ОБОСНОВАНО. Чтобы
 * проверить разрыв сценарием, надо оборвать поток в середине, что-то
 * написать и восстановить связь — это медленно и мигает. А само правило —
 * три числа без единой зависимости, и именно в нём живёт вся страховка
 * от потерянного сообщения.
 */

describe("что делать с репликой из события", () => {
  it("номер сразу за курсором — применяем", () => {
    expect(carried(11, 10)).toBe("применить");
  });

  it("между курсором и репликой есть невиданное — идём в догон", () => {
    // Самая опасная ошибка: применить её сейчас — значит перешагнуть
    // через пропущенное навсегда, потому что курсор уйдёт за него.
    expect(carried(13, 10)).toBe("догнать");
  });

  it("реплика с номером курсора — уже видели, никуда не идём", () => {
    expect(carried(10, 10)).toBe("уже видели");
  });

  it("повтор старой реплики не гонит в догон", () => {
    // Вкладка переподключилась и получила хвост заново. Догон вернул бы
    // то же самое: на тысяче вкладок это тысяча запросов на ровном месте.
    expect(carried(5, 10)).toBe("уже видели");
  });

  it("первая реплика свежей вкладки — курсор ноль", () => {
    expect(carried(1, 0)).toBe("применить");
  });
});
