/**
 * Разбор списка договорённостей — чистая часть экрана работы.
 *
 * Проверки здесь не про вёрстку, а про два свойства, которые легко
 * потерять и трудно заметить глазами:
 *   ① договорённость с незнакомым статусом не должна исчезать с экрана;
 *   ② цитата, дословно повторяющая текст договорённости, не должна
 *      показываться дважды — иначе человек привыкает пролистывать
 *      повтор и перестаёт читать источник вообще (А-2).
 */
import { describe, expect, it } from "vitest";
import type { Agreement } from "./api.js";
import { awaiting, quoteAddsNothing, refused, strays } from "./work.js";

function agreement(status: string, id = status): Agreement {
  return {
    id,
    conversationId: "к-1",
    conversationTitle: "Канал",
    text: "текст",
    status,
    proposedBy: { id: "а-1", name: "Агент" },
    confirmedBy: null,
    createdAt: "2026-09-06T10:00:00.000Z",
    citations: [],
  };
}

describe("раскладка договорённостей", () => {
  it("ждут решения только предложенные", () => {
    const all = [agreement("proposed"), agreement("confirmed"), agreement("rejected")];
    expect(awaiting(all).map((a) => a.id)).toEqual(["proposed"]);
  });

  it("отклонённые лежат отдельно", () => {
    const all = [agreement("proposed"), agreement("rejected")];
    expect(refused(all).map((a) => a.id)).toEqual(["rejected"]);
  });

  it("подтверждённая не попадает никуда: её место — в задачах", () => {
    // Иначе одно и то же видно дважды, и список задач перестаёт быть
    // ответом на вопрос «что мы должны сделать».
    const one = [agreement("confirmed")];
    expect(awaiting(one)).toHaveLength(0);
    expect(refused(one)).toHaveLength(0);
    expect(strays(one)).toHaveLength(0);
  });

  it("незнакомый статус не исчезает молча", () => {
    // Статусы задаёт база, и завтра их может стать больше. Договорённость,
    // выпавшая из всех списков, — это потерянная работа, а не пустяк.
    const all = [agreement("proposed"), agreement("отложена")];
    expect(strays(all).map((a) => a.id)).toEqual(["отложена"]);
  });
});

describe("цитата против текста договорённости", () => {
  it("дословный повтор показывать второй раз незачем", () => {
    expect(quoteAddsNothing("Я выгружу логи к четвергу.", "Я выгружу логи к четвергу.")).toBe(true);
  });

  it("разница только в пробелах и регистре — это тот же текст", () => {
    expect(quoteAddsNothing("Я выгружу логи  к четвергу.", "я выгружу логи к четвергу.")).toBe(
      true,
    );
  });

  it("приставка с именем говорящего не делает цитату новой", () => {
    // Так выглядит сегодняшний разбор: текст договорённости — это реплика
    // с приписанным именем. Два одинаковых абзаца подряд человек перестаёт
    // читать оба.
    expect(
      quoteAddsNothing(
        "Светлана: Я подготовлю договор к четвергу.",
        "Я подготовлю договор к четвергу.",
      ),
    ).toBe(true);
  });

  it("пустая цитата ничего не заменяет", () => {
    expect(quoteAddsNothing("Я подготовлю договор", "")).toBe(false);
  });

  it("переформулированную договорённость показываем вместе с источником", () => {
    // Ради этого случая всё и делается: когда К3 научится формулировать,
    // человек обязан видеть И формулировку, И то, из чего она выросла.
    expect(quoteAddsNothing("Выгрузить логи за август до четверга", "ладно, сделаю")).toBe(false);
  });
});
