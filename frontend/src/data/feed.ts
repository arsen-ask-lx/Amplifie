import { isTombstone, type Message, type SyncLine } from "./api.js";

/**
 * Как строки от сервера становятся лентой.
 *
 * ⚠️ ВЫНЕСЕНО ИЗ `useChat`, КОГДА ТОТ ПЕРЕВАЛИЛ ЗА ПРЕДЕЛ РАЗМЕРА, но шов
 * не выдуман под предел. Здесь ЧИСТЫЕ функции: на входе то, что есть,
 * и то, что пришло, на выходе — то, что показывать. Ни запросов, ни
 * состояния, ни адресной строки. `useChat` отвечает на другой вопрос —
 * когда спрашивать сервер и что делать с ответом.
 *
 * Разница видна по проверкам: на этот файл они пишутся без браузера
 * и без стека (`merge.test.ts`), а на хук — только через экран.
 */

/**
 * Своя реплика, ещё не дошедшая до сервера.
 *
 * ⚠️ ПОЛЕ ЖИВЁТ ТОЛЬКО ЗДЕСЬ И НЕ ПРИХОДИТ С СЕРВЕРА. `Message` повторяет
 * форму ответа сервера, и дописывать в неё наши выдумки нельзя: однажды
 * кто-то решит, что состояние доставки хранится в базе. Поэтому отдельный
 * тип, а не лишнее поле в общем.
 */
export type Local = Message & { state?: "идёт" | "не ушло" };

/**
 * Слияние по идентификатору: догон отвечает «вот как теперь», а не «вот
 * что дописали».
 *
 * ⚠️ ДОГОН МОЖЕТ ПРИНЕСТИ РЕПЛИКУ, КОТОРАЯ УЖЕ ЕСТЬ. Так и должно быть:
 * правка старой реплики приезжает ею же самой. Поэтому известный
 * идентификатор ЗАМЕЩАЕТСЯ, а не добавляется, — иначе исправленная
 * реплика встала бы в ленту второй раз.
 *
 * ⚠️ МЕСТО В ЛЕНТЕ БЕРЁТСЯ ИЗ `seq`, А НЕ ИЗ ПОРЯДКА ОТВЕТА. Сервер
 * упорядочивает догон по номеру ИЗМЕНЕНИЯ, и исправленная позавчерашняя
 * реплика приезжает последней. Место в разговоре у неё при этом прежнее.
 *
 * ⚠️ НАДГРОБИЕ УБИРАЕТ РЕПЛИКУ, А НЕ ДОБАВЛЯЕТ ПУСТУЮ. Текста в нём нет,
 * и показывать нечего: удалённое исчезает с экрана у всех, а не только
 * у того, кто удалил.
 */
export function merge(current: Message[], incoming: SyncLine[], keep?: number): Message[] {
  if (incoming.length === 0) return current;
  const byId = new Map(current.map((m) => [m.id, m]));
  for (const line of incoming) {
    if (isTombstone(line)) {
      byId.delete(line.id);
      continue;
    }
    /**
     * ⚠️ ЗАПИСАННАЯ РЕПЛИКА ВЫТЕСНЯЕТ СВОЙ ЧЕРНОВИК. Черновик лежит
     * в ленте под своим ключом, а пришедшая с сервера — под настоящим
     * `id`: без этой строки они уживались бы рядом как две разные
     * реплики. Ждать ответа на отправку нельзя — догон умеет принести
     * запись РАНЬШЕ, чем ответит сама отправка, и тогда человек на
     * мгновение видит своё сообщение дважды.
     */
    if (line.clientMsgId && line.clientMsgId !== line.id) byId.delete(line.clientMsgId);
    byId.set(line.id, line);
  }
  const all = [...byId.values()].sort((a, b) => a.seq - b.seq);

  /**
   * ⚠️ ОКНО РЕЖЕТ СВЕРХУ И ТОЛЬКО СВЕРХУ (Р-023). Рез снизу — потеря
   * только что сказанного, худшая поломка ленты из возможных.
   *
   * ⚠️ ОКНО ЗАДАЁТСЯ НЕ ВСЕГДА, И ЭТО ГЛАВНОЕ. Тем же слиянием
   * догружается старое, когда человек листает назад: там резать нельзя —
   * мы выбросили бы ровно то, за чем он туда пошёл. Поэтому окно
   * не «настройка слияния», а решение зовущего: знает ли он, что
   * человек сейчас внизу.
   */
  return keep === undefined || all.length <= keep ? all : all.slice(-keep);
}

/** Есть ли за краями ленты незагруженное: старше нижнего, новее верхнего. */
export interface Edges {
  older: boolean;
  newer: boolean;
}

/**
 * Строки, которым место внутри ленты (task-099).
 *
 * ⚠️ ЛЕНТА — НЕПРЕРЫВНЫЙ ОТРЕЗОК, И ВЛИВАТЬ ЗА ЕГО КРАЙ НЕЛЬЗЯ. Страница
 * с края берёт номер крайней строки своим курсором: вставь за край
 * незнакомую реплику — и всё между ней и отрезком не загрузится никогда.
 * Такая строка не теряется: её привезёт страница с того края.
 *
 * Показанная строка проходит всегда — правка и надгробие обязаны доехать.
 * Строка внутри отрезка проходит тоже: между двумя показанными могла
 * появиться реплика, записанная позже страницы. Без краёв проходит всё,
 * и лента в конце ведёт себя как прежде.
 */
export function inside(current: Message[], incoming: SyncLine[], edges: Edges): SyncLine[] {
  if (current.length === 0 || (!edges.older && !edges.newer)) return incoming;
  const known = new Set(current.map((one) => one.id));
  const lowest = current[0]?.seq ?? 0;
  const highest = maxSeq(current);
  return incoming.filter(
    (line) =>
      known.has(line.id) ||
      !((edges.newer && line.seq > highest) || (edges.older && line.seq < lowest)),
  );
}

/**
 * Номер края ленты для догрузки страницы — по ЗАПИСАННЫМ репликам.
 *
 * ⚠️ ЧЕРНОВИК КРАЕМ НЕ БЫВАЕТ (task-099). У него дробный номер «последний
 * плюс половина»: отправка из давнего сбрасывает ленту до одного черновика,
 * и короткая лента сама звала «более раннее» от его номера — сервер отвечал
 * отказом, а успей подгрузка раньше конца, старое склеилось бы с концом.
 */
export function writtenEdge(messages: Message[], at: "first" | "last"): number | undefined {
  const written = messages.filter((one) => Number.isInteger(one.seq));
  return (at === "first" ? written[0] : written.at(-1))?.seq;
}

/**
 * Эта реплика уже в загруженном окне ленты (task-106).
 *
 * ⚠️ РАДИ ЭТОГО ПРАВИЛА ХОД ПО ПОПАДАНИЯМ ПОИСКА СТАЛ БЕСШОВНЫМ. Переход
 * к реплике идёт адресом, а на смену адреса лента грузила окно заново —
 * то есть стрелка «следующее совпадение» стоила запроса и полной
 * перерисовки, хотя нужная реплика была на экране. Если номер внутри
 * окна, грузить нечего: остаётся прокрутка и одна вспышка.
 *
 * Черновики не считаются: у них дробный номер и на сервере их нет.
 */
export function inWindow(messages: Message[], seq: number): boolean {
  return messages.some((one) => Number.isInteger(one.seq) && one.seq === seq);
}

/**
 * Только те строки догона, что относятся к открытому разговору.
 *
 * ⚠️ ДО ЭТОГО В ЛЕНТУ ЛОЖИЛИСЬ ВСЕ КОМНАТЫ ПРОСТРАНСТВА (Д-11). Их никто
 * не читал: при показе они отсекались, при переключении разговора
 * выбрасывались. То есть память вкладки росла ровно на то, что заведомо
 * будет выброшено, — и росла тем быстрее, чем оживлённее СОСЕДНИЕ каналы.
 *
 * Ничего не теряется: открыв другой разговор, человек грузит его историю
 * тем же путём, что и всегда.
 */
export function ofRoom(incoming: SyncLine[], roomId: string | null): SyncLine[] {
  if (!roomId) return [];
  return incoming.filter((line) => line.conversationId === roomId);
}

/**
 * Полоска закреплённого после догона.
 *
 * ⚠️ ПЕРЕСТРАИВАЕТСЯ ИЗ ТОГО ЖЕ ОТВЕТА, ЧТО И ЛЕНТА. Раньше закрепление
 * приезжало ОТДЕЛЬНЫМ запросом по звонку — второй путь к тому же событию.
 * Два пути к одному событию расходятся молча: у нас это уже случалось.
 *
 * Первая загрузка полоски всё равно остаётся отдельной дверью, и это не
 * противоречие: закреплённая реплика может лежать на тысячу строк выше
 * загруженного окна, и догон о ней ничего не скажет — он рассказывает
 * про ИЗМЕНЕНИЯ, а не про историю.
 *
 * Порядок — свежие сверху, по времени закрепления: тот же, что у сервера.
 */
export function mergePinned(
  current: Message[],
  incoming: SyncLine[],
  roomId: string | null,
): Message[] {
  if (!roomId || incoming.length === 0) return current;

  const mine = incoming.filter((line) => line.conversationId === roomId);
  if (mine.length === 0) return current;

  const byId = new Map(current.map((m) => [m.id, m]));
  const before = byId.size;
  let added = 0;

  for (const line of mine) {
    // Закреплённой реплика остаётся, только пока жива и пока отметка стоит.
    // Оба «нет» ведут в одно и то же место, и хорошо, что в одно.
    if (isTombstone(line) || line.pinnedAt === null) byId.delete(line.id);
    else {
      byId.set(line.id, line);
      added += 1;
    }
  }

  // Полоска не изменилась — отдаём ТУ ЖЕ ссылку, а не новый список:
  // иначе каждая перерисовка ленты перерисовывала бы и её.
  if (byId.size === before && added === 0) return current;
  return [...byId.values()].sort(byPinnedAtDesc);
}

/** Свежее закрепление сверху — тот же порядок, что отдаёт сервер. */
function byPinnedAtDesc(a: Message, b: Message): number {
  return (b.pinnedAt ?? "").localeCompare(a.pinnedAt ?? "");
}

export const maxSeq = (messages: Message[]) => messages.reduce((top, m) => Math.max(top, m.seq), 0);
