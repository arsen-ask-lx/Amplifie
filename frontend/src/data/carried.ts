/**
 * Что делать с репликой, приехавшей в событии (task-085).
 *
 * ⚠️ ОТДЕЛЬНЫМ ЗНАНИЕМ, А НЕ ТРЕМЯ СТРОКАМИ В ЭФФЕКТЕ. Это правило —
 * единственная страховка от второго пути доставки: событие применяется
 * только тогда, когда оно продолжает курсор клиента, и ни в одном другом
 * случае. Ошибка здесь не видна глазами и не ловится замером — она видна
 * через сутки как «у половины людей пропало сообщение».
 *
 * Внутри эффекта это правило не проверить: там браузер, поток и состояние.
 * Здесь — три числа и ни одной зависимости.
 */

export type Carried =
  /** Номер идёт сразу за курсором — показываем, никуда не ходим. */
  | "применить"
  /** Между курсором и этой репликой есть невиданное — идём в догон. */
  | "догнать"
  /** Номер не больше курсора — это мы уже показывали. */
  | "уже видели";

export function carried(seq: number, cursor: number): Carried {
  if (seq === cursor + 1) return "применить";
  // ⚠️ СТРОГО БОЛЬШЕ, А НЕ «НЕ РАВНО». Реплика с номером МЕНЬШЕ курсора —
  // это повтор (звонок продублировался, вкладка переподключилась и получила
  // хвост заново). Идти за ней в догон незачем: догон вернёт то же самое,
  // а на тысяче вкладок это тысяча лишних запросов на ровном месте.
  if (seq > cursor) return "догнать";
  return "уже видели";
}
