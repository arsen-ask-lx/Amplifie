import type { Conversation, Message } from "./api.js";

/**
 * Строка панели после приехавшей реплики (task-092).
 *
 * ⚠️ ЭТО ПЕРВОЕ МЕСТО, ГДЕ НЕПРОЧИТАННОЕ СЧИТАЕТ НЕ СЕРВЕР, и потому
 * правило вынесено сюда целиком, а не разложено по эффектам. Ошибка здесь
 * не ловится ни типами, ни замером: она видна человеку через день как
 * «висит единичка, а читать нечего» — или, хуже, как непоказанный зов.
 *
 * ⚠️ ЭТО ПРИРАЩЕНИЕ, А НЕ СЧЁТ, и разница принципиальная. Сервер считает
 * непрочитанное запросом от отметки прочтения (`unread.ts`); здесь мы лишь
 * двигаем его ответ на один известный шаг. Второго способа посчитать
 * не заводится — заведись он, два числа разошлись бы молча.
 *
 * ⚠️ ПРИМЕНЯЕТСЯ ТОЛЬКО К РЕПЛИКЕ, ПРИЗНАННОЙ НЕПРЕРЫВНОЙ (`carried.ts`).
 * Правило Телеграма: `local_pts + pts_count === pts` — иначе разрыв
 * и полное перечитывание. Без этого условия приращение накапливало бы
 * ошибку, и никто бы не заметил.
 *
 * Разбор источников: dock/reference/панель-без-перечитывания-2026-09.md
 */

export interface Who {
  /** Кто смотрит: свои реплики непрочитанными не считаются (Р-029). */
  me: string;
  /** Какой разговор открыт: в нём человек видит реплику сразу. */
  openId: string | null;
  /**
   * Кого позвали этой репликой — список приезжает в событии.
   *
   * Клиент посчитать это сам не может: упоминание живёт в тексте (Р-020),
   * и разбор текста здесь был бы второй разметкой рядом с серверной.
   */
  mentioned: string[];
}

/**
 * Поднять строку разговора и дописать ей счётчики.
 *
 * ⚠️ СТРОКИ НЕТ — НИЧЕГО НЕ ДЕЛАЕМ. Панель грузит порциями (Р-037),
 * и разговора может не быть среди загруженных: он в свёрнутой папке или
 * за краем «Недавних». Выдумать строку нельзя — у выдуманной нет ни прав,
 * ни названия, ни отметки прочтения; она появится при первом полном
 * перечитывании, посчитанная сервером.
 *
 * ⚠️ ВЕТКА В КАНАЛ НЕ СВОРАЧИВАЕТСЯ. Сервер считает свежесть
 * и непрочитанное по репликам ЭТОГО разговора; свернём ветку здесь —
 * панель разойдётся с сервером при первом же перечитывании.
 *
 * Порядок строк не трогается: его считает сервер. Здесь меняется только
 * то, ПО ЧЕМУ он сортирует, — а сортировку делает панель тем же правилом,
 * что и всегда.
 */
export function bumped(items: Conversation[], line: Message, who: Who): Conversation[] {
  const at = items.findIndex((one) => one.id === line.conversationId);
  const row = items[at];
  if (!row) return items;

  const mine = line.author.id === who.me;
  // Открытый разговор человек видит: ни счётчик, ни зов в нём не растут.
  const watching = who.openId === line.conversationId;
  const unseen = !mine && !watching;

  const next = [...items];
  next[at] = {
    ...row,
    lastAt: line.createdAt,
    unread: row.unread + (unseen ? 1 : 0),
    mentions: row.mentions + (unseen && who.mentioned.includes(who.me) ? 1 : 0),
  };
  return next;
}

/**
 * Строка панели после ответа на отметку «прочитано» (task-097).
 *
 * ⚠️ ЧИСЛО — СЕРВЕРНОЕ, А НЕ ВЫЧТЕННОЕ ИЗ ОКНА ЛЕНТЫ. Поправка на свои
 * отметки считается по репликам открытого чата; у покинутого чата их
 * в ленте уже нет, у чата длиннее окна — не все. Число оставалось гореть
 * на прочитанном. Сервер отвечает остатком — как `still_unread_count`
 * у Telegram, — и он точнее любого нашего счёта.
 *
 * ⚠️ УПОМИНАНИЯ ГАСНУТ ТОЛЬКО ВМЕСТЕ С НУЛЁМ. Непрочитанный зов — это
 * непрочитанная реплика (Р-031): остаток ноль значит и зовов ноль;
 * остаток больше нуля о зовах не говорит ничего, и их число не трогаем.
 *
 * Номер прочтения — только вперёд: ответ на старую отметку не откатывает
 * строку, которую уже подвинула свежая.
 */
export function readApplied(
  items: Conversation[],
  conversationId: string,
  seq: number,
  unread: number,
): Conversation[] {
  const at = items.findIndex((one) => one.id === conversationId);
  const row = items[at];
  if (!row || seq < row.readSeq) return items;

  const next = [...items];
  next[at] = {
    ...row,
    readSeq: seq,
    unread,
    mentions: unread === 0 ? 0 : row.mentions,
  };
  return next;
}
