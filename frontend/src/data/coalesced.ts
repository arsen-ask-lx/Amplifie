/**
 * «Делай сразу, потом не чаще раза в окно» (task-086).
 *
 * ⚠️ ЗАЧЕМ ЭТО ВООБЩЕ. Список чатов перечитывается на каждый звонок потока:
 * непрочитанное и порядок меняются и от чужой реплики. В живом разговоре
 * это десять перечитываний на десять реплик — у КАЖДОЙ открытой вкладки.
 * Замерено: 40 вкладок, 10 реплик подряд — 400 перечитываний панели
 * и 1600 запросов к базе.
 *
 * ⚠️ СНАЧАЛА СРАЗУ, И ЭТО ГЛАВНОЕ РЕШЕНИЕ ЗДЕСЬ. Простая отсрочка
 * («подождём три секунды и перечитаем») сделала бы счётчик непрочитанного
 * медленным у всех и всегда — то есть испортила бы то, чем человек
 * пользуется, ради того, чего он не видит. Поэтому первый вызов проходит
 * немедленно, а окно закрывает только ПОВТОРНЫЕ.
 *
 * ⚠️ И ХВОСТ ОБЯЗАТЕЛЕН. Если во время окна что-то пришло, по его закрытии
 * делается ещё один вызов — иначе последнее изменение осталось бы
 * не показанным до следующего звонка, а в затихшем чате это «навсегда».
 *
 * Тот же приём и тот же порядок величины, что у отметок прочтения (Р-029):
 * пока человек листает, отметки копятся и уходят одной.
 */
export function coalesced(run: () => void, windowMs: number): () => void {
  let closing: ReturnType<typeof setTimeout> | undefined;
  let waiting = false;

  const fire = () => {
    run();
    closing = setTimeout(() => {
      closing = undefined;
      if (!waiting) return;
      waiting = false;
      fire();
    }, windowMs);
  };

  return () => {
    if (closing) {
      waiting = true;
      return;
    }
    fire();
  };
}
