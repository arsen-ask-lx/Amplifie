import bridge from "../../assets/bridge.webp";
import eclipse from "../../assets/eclipse.webp";

/**
 * Картинки входа и числа растра к каждой (task-026).
 *
 * ⚠️ ЧИСЛА ЖИВУТ РЯДОМ С КАРТИНКОЙ, А НЕ В КОДЕ ХОЛСТА. Их подбирают
 * глазом под конкретное изображение: у фотографии с плавными тонами одни,
 * у гравюры, нарисованной линиями, другие. Общая настройка «на все
 * картинки» — это среднее, при котором плохо выглядит каждая.
 *
 * Подобрано владельцем ползунками на настоящей половине экрана, а не
 * назначено: единственный способ проверить вид — посмотреть на него.
 */
export interface Picture {
  /** Адрес файла. Серый, сжатый; растр накладывается уже в браузере. */
  src: string;
  /**
   * Сколько усреднять перед растром, в пикселях.
   *
   * Ноль для фотографии: у неё тона и так плавные. Гравюре нужен сдвиг
   * от нуля — она сама нарисована линиями, и без усреднения сетка
   * ложится растром на растр, а две регулярные сетки дают рябь.
   */
  blur: number;
  contrast: number;
  /** Сдвиг светлоты после контраста. Минус — темнее. */
  bright: number;
}

/**
 * ⚠️ ЗАПОЛНЯЮТ ВСЕ ОДИНАКОВО, И ВЫБОРА ЗДЕСЬ НЕТ НАМЕРЕННО.
 *
 * Была попытка дать картинке настройку «заполнить или показать целиком»:
 * гравюру резало по высоте, и хотелось увидеть её всю. Вышло хуже —
 * соседние экраны стали занимать разную площадь, и переход между ними
 * читался как сбой вёрстки.
 *
 * Правильным оказалось не менять способ посадки, а перекадрировать
 * ФАЙЛ под ту форму, в которой его показывают: у затмения из 3:4 вырезан
 * кадр 0.86, где солнце, дерево и горизонт целы. Настройка убрана,
 * чтобы к этому вопросу не возвращались второй раз.
 */

/** Мост через воду. Дверь: вход, установка, приглашение. */
export const МОСТ: Picture = { src: bridge, blur: 0, contrast: 1.4, bright: 0 };

/** Затмение, перьевая гравюра. Первый шаг установки. */
export const ЗАТМЕНИЕ: Picture = { src: eclipse, blur: 0.5, contrast: 1.3, bright: -16 };
