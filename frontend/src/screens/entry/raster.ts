/**
 * Растр входного экрана: серая фотография → две краски (task-022).
 *
 * ⚠️ ЧИСТАЯ АРИФМЕТИКА, БЕЗ DOM. Холст живёт в `Halftone.tsx`; здесь только
 * числа — иначе это нечем проверить быстрым тестом, а проверять надо именно
 * это: неверная матрица даёт полосы, и на глаз причину ищут в фотографии.
 *
 * ⚠️ ПОЧЕМУ РАСТР СЧИТАЕТСЯ У НАС, А НЕ ЛЕЖИТ ГОТОВЫМ В ФАЙЛЕ. Готовый резок
 * ровно при показе один к одному. Высота окна у всех разная, множитель экрана
 * бывает 1, 1.25, 2 — на любом другом размере точка попадает между пикселями,
 * и вместо растра выходит рябь.
 */

/** Середина шкалы: вокруг неё разводится контраст. */
const MIDDLE = 128;

/**
 * ⚠️ ПОЧЕМУ ЗДЕСЬ ЕСТЬ `as number`, А БОЛЬШЕ НИГДЕ В ПРОЕКТЕ НЕТ.
 *
 * Строгая проверка индексов (`noUncheckedIndexedAccess`) считает всякое
 * чтение по числу возможно пустым. Она права там, где индекс приходит
 * снаружи: в карте настроек, в разборе ответа. Здесь другой случай —
 * буфер плотный, а индекс посчитан из его же длины двумя строками выше,
 * поэтому промаха нет по построению.
 *
 * Проверять его на каждой точке значило бы поставить ветвление на
 * двенадцать миллионов чтений в одном кадре ради условия, которое
 * не может стать ложным. Написано утверждением и объяснено один раз,
 * а не спрятано через `?? 0`: ноль — это чёрный, и промах превратился бы
 * в чёрное пятно вместо отказа.
 */

/**
 * Матрица Байера порядка `order` — упорядоченные пороги, тот самый
 * регулярный растр, который выбрал владелец (сетка 8).
 *
 * Строится удвоением: каждая ячейка превращается в четыре по правилу
 * `4v, 4v+2 / 4v+3, 4v+1`. Отсюда и требование к порядку — степень двойки.
 */
export function bayer(order: number): number[][] {
  if (order < 2 || (order & (order - 1)) !== 0) {
    throw new Error(`порядок матрицы Байера — степень двойки от 2, получено ${order}`);
  }

  // Плоский массив, пока строим: вложенные ряды нужны только на выходе,
  // а внутри они дали бы вдвое больше чтений по индексу.
  let side = 2;
  let flat = [0, 2, 3, 1];

  while (side < order) {
    const wide = side * 2;
    const next = new Array<number>(wide * wide);
    for (let y = 0; y < side; y++) {
      for (let x = 0; x < side; x++) {
        const value = (flat[y * side + x] as number) * 4;
        next[y * wide + x] = value;
        next[y * wide + x + side] = value + 2;
        next[(y + side) * wide + x] = value + 3;
        next[(y + side) * wide + x + side] = value + 1;
      }
    }
    flat = next;
    side = wide;
  }

  return Array.from({ length: side }, (_, y) => flat.slice(y * side, y * side + side));
}

/**
 * Четыре байта на точку → одна светлота, с контрастом вокруг середины
 * и сдвигом яркости.
 *
 * Контраст разводит середину и НЕ трогает края: чёрное остаётся чёрным,
 * белое белым. Уползи они — растр теряет и плотность листвы, и чистое небо
 * разом, а вернуть это ползунком уже нельзя.
 *
 * ⚠️ ЯРКОСТЬ ПРИМЕНЯЕТСЯ ПОСЛЕ КОНТРАСТА, И ПОРЯДОК ЗДЕСЬ ЗНАЧИМ.
 * Наоборот — и контраст разводил бы уже сдвинутую середину, то есть
 * два ползунка мешали бы друг другу: подобранное сегодня переставало бы
 * значить то же самое завтра. Края отсекаются последними, поэтому
 * перебор яркости гасит картинку, но не выворачивает её.
 */
export function toGray(rgba: Uint8ClampedArray, contrast: number, bright = 0): Float32Array {
  const gray = new Float32Array(rgba.length / 4);
  for (let at = 0, out = 0; at < rgba.length; at += 4, out++) {
    const light =
      0.299 * (rgba[at] as number) +
      0.587 * (rgba[at + 1] as number) +
      0.114 * (rgba[at + 2] as number);
    const spread = (light - MIDDLE) * contrast + MIDDLE + bright;
    gray[out] = spread < 0 ? 0 : spread > 255 ? 255 : spread;
  }
  return gray;
}

/**
 * Порог по матрице — на месте, тем же массивом.
 *
 * На месте не ради скорости, а ради памяти: на большом экране это
 * четыре миллиона чисел, и вторая их копия пересчитывается при каждом
 * движении рамки окна.
 */
export function ordered(
  gray: Float32Array,
  width: number,
  height: number,
  matrix: number[][],
): void {
  const side = matrix.length;
  // Ряды разворачиваются в один массив один раз: во внутреннем цикле
  // это снимает половину чтений по индексу.
  const flat = matrix.flat();
  // Пороги ложатся в середины ступеней: без половины крайняя ступень
  // получила бы порог 0 и не срабатывала бы никогда.
  const step = 255 / (side * side);

  for (let y = 0; y < height; y++) {
    const row = (y % side) * side;
    for (let x = 0; x < width; x++) {
      const at = y * width + x;
      const edge = ((flat[row + (x % side)] as number) + 0.5) * step;
      gray[at] = (gray[at] as number) > edge ? 255 : 0;
    }
  }
}
