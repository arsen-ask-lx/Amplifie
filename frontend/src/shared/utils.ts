import { type ClassValue, clsx } from "clsx";
import { extendTailwindMerge } from "tailwind-merge";

/**
 * Шкала набора — та же, что объявлена в `styles.css` (`--text-*`).
 *
 * ⚠️ ЭТОТ СПИСОК ЕСТЬ ВТОРАЯ ЗАПИСЬ ОДНОГО ЗНАНИЯ, И ЭТО ОСОЗНАННАЯ ЦЕНА.
 * `tailwind-merge` ничего не знает про наши имена: для него `text-body`
 * и `text-aside` — два незнакомых класса, а не две ступени одной шкалы.
 * Не сказав ему, мы получаем молчаливый отказ: дописанный сверху размер
 * не побеждает и не сообщает об этом.
 *
 * Взамен работает обещание, ради которого `cn` и заведён (ниже).
 * Появится новая ступень — её надо добавить сюда; забудешь, и она просто
 * перестанет перебиваться, как было с `text-aside` на экране входа.
 */
const SIZES = ["mark", "aside", "body", "lead", "head", "brand"];

/**
 * Собрать классы и разрешить их спор.
 *
 * Нужен потому, что у Tailwind побеждает не последний класс в строке,
 * а тот, что стоит позже в собранном CSS. Строка `"p-2 p-4"` даёт
 * непредсказуемый отступ. `twMerge` выкидывает проигравшего заранее,
 * и «поверх компонента дописал класс» начинает работать так, как выглядит.
 *
 * ⚠️ ОБЕЩАНИЕ ДЕЙСТВОВАЛО НЕ ВЕЗДЕ. Для родных классов Tailwind оно
 * работало с первого дня, а для нашей шкалы набора — нет: `text-body`
 * из основы кнопки побеждал `text-aside`, дописанный снаружи, и обойти
 * это можно было только важностью. Один такой обход уже стоял на экране
 * входа. Теперь спор решается здесь, и важности не нужны.
 */
const twMerge = extendTailwindMerge({
  extend: {
    classGroups: {
      "font-size": [{ text: SIZES }],
    },
  },
});

export function cn(...parts: ClassValue[]): string {
  return twMerge(clsx(parts));
}
