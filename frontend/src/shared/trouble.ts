/**
 * Что означает код ответа на каждой нашей ручке.
 *
 * ⚠️ ГЛАВНОЕ, ЧТО ВИДНО ТОЛЬКО ЗДЕСЬ: ОДИН КОД ЗНАЧИТ РАЗНОЕ.
 *
 *   409 — при входе «почта занята», на доске «размыкатель разомкнут»;
 *   503 — у агента «модель не подключена», у ключей «сервер не настроен
 *         для хранения секретов».
 *
 * Пока эти карты лежали по экранам (пять файлов до task-012), расхождение
 * было невидимо и выглядело как небрежность. Собранные в один файл, они
 * показывают правду: **общего словаря кодов у нас нет и быть не может**,
 * потому что код HTTP описывает разговор, а не предмет.
 *
 * Общее здесь другое и оно настоящее: КОД РАЗБИРАЕТСЯ ОДИН РАЗ. Экран
 * получает причину и пишет свои слова — на доске и в чате они разные,
 * и это законно. А вот «что значит 504» разным быть не должно.
 */
import { statusOf } from "./failure.js";

/** Отказ на пути «спросить модель»: чат, доска, проверка связи. */
export type Trouble =
  /** Размыкатель разомкнут: два отказа подряд, нужен человек (task-011). */
  | "размыкатель"
  /** Ни моста, ни ключа — спрашивать нечем. */
  | "нет-модели"
  /** Мост взял работу и не ответил в срок. */
  | "мост-молчит"
  /** Модель ответила отказом. */
  | "модель-отказала"
  /** Что-то другое, включая «до сервера не дошли». */
  | "иное";

export function troubleOf(error: unknown): Trouble {
  switch (statusOf(error)) {
    case 409:
      return "размыкатель";
    case 503:
      return "нет-модели";
    case 504:
      return "мост-молчит";
    case 502:
      return "модель-отказала";
    default:
      return "иное";
  }
}

/** Отказ при сохранении ключа поставщика. */
export type KeyTrouble =
  /** Ключ не той формы: не тот префикс или слишком короткий. */
  | "не-та-форма"
  /** У сервера нет мастер-ключа — шифровать нечем (Р-016). */
  | "негде-хранить"
  | "иное";

export function keyTroubleOf(error: unknown): KeyTrouble {
  switch (statusOf(error)) {
    case 422:
      return "не-та-форма";
    case 503:
      return "негде-хранить";
    default:
      return "иное";
  }
}

/** Отказ при входе, регистрации и приглашении. */
export type AuthTrouble =
  | "не-та-пара"
  | "ссылка-не-работает"
  | "регистрация-закрыта"
  | "почта-занята"
  | "слишком-часто"
  | "иное";

export function authTroubleOf(error: unknown): AuthTrouble {
  switch (statusOf(error)) {
    case 401:
      return "не-та-пара";
    case 403:
      return "регистрация-закрыта";
    case 404:
      return "ссылка-не-работает";
    case 409:
      return "почта-занята";
    case 429:
      return "слишком-часто";
    default:
      return "иное";
  }
}
