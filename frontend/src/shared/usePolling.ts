import { useEffect } from "react";

/**
 * Перечитывать, пока экран открыт.
 *
 * ЗАЧЕМ ОТДЕЛЬНО. До task-012 «Агенты» и «Своя подписка» опрашивали
 * сервер каждые 4 секунды ДВУМЯ таймерами — притом что второй экран
 * рисуется внутри первого, а состояние моста приходит в обоих ответах.
 * Два таймера на один вопрос — это не удвоенная свежесть, а удвоенный
 * шум и два разных момента правды.
 *
 * ⚠️ Опрос — временная мера. Живые обновления идут звонком по SSE (Р-006);
 * сюда они не дотянуты, потому что состояние моста меняется не событием
 * в базе, а тем, что кто-то закрыл окно терминала.
 */
export function usePolling(tick: () => void | Promise<void>, everyMs: number): void {
  useEffect(() => {
    void tick();
    const timer = setInterval(() => void tick(), everyMs);
    return () => clearInterval(timer);
  }, [tick, everyMs]);
}
