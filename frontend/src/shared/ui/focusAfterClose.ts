/**
 * Поставить фокус туда, куда нужно, ПОСЛЕ того как меню или окно отпустит его.
 *
 * ⚠️ ЗАЯВКА, А НЕ ТАЙМЕРЫ. Меню и окна Radix держат фокус внутри себя, пока
 * доигрывают закрытие, и возвращают его сами — на кнопку, откуда их открыли.
 * Поле ввода, поставившее себе фокус раньше, тут же его теряло. Прежнее
 * лечение — три попытки через 0, 60 и 150 мс — было гонкой: закрытие иногда
 * длилось дольше, и владелец ловил «Ответить» без курсора ровно в первый раз
 * (26.09). Здесь фокус ставится в миг, когда окно само решает, куда его деть:
 * в его `onCloseAutoFocus`.
 *
 * Заявка живёт две секунды: если за это время ничего не закрылось, значит
 * фокус и так встал, и отложенный запрос сработал бы невпопад — на закрытии
 * какого-нибудь другого меню минутой позже.
 */
const LIFETIME_MS = 2000;

let pending: { run: () => void; until: number } | null = null;

export function focusAfterClose(run: () => void): void {
  pending = { run, until: Date.now() + LIFETIME_MS };
}

/** Зовёт закрывающееся окно. `true` — заявка была, и фокус поставлен ею. */
export function claimFocus(): boolean {
  const claim = pending;
  pending = null;
  if (!claim || Date.now() > claim.until) return false;
  claim.run();
  return true;
}

/**
 * Поле ввода открытого чата — чтобы щелчок по УЖЕ открытому чату в панели
 * вернул курсор в поле (владелец 26.09: «включил чат — начал печатать»).
 * Смена чата ставит фокус сама, при рождении поля; повторный щелчок
 * ничего не меняет в адресе, и полю не по чему узнать, что его позвали.
 */
let field: (() => void) | null = null;

/** Поле сообщает, как его сфокусировать. Возвращает отписку. */
export function registerField(focus: () => void): () => void {
  field = focus;
  return () => {
    if (field === focus) field = null;
  };
}

export function focusField(): void {
  field?.();
}
