import { toast } from "./toast.js";

/**
 * Скопировать в буфер обмена.
 *
 * Браузер может не дать: буфер закрыт настройками приватности, и это
 * не поломка, а выбор человека. Возвращаем ответ, а не бросаем: обе
 * стороны — обычный ход, и обе показываются словами, а не молчанием.
 *
 * До task-012 этот же `try/catch` с тем же текстом стоял в двух экранах —
 * в приглашении и в подключении моста.
 *
 * ⚠️ НАРУЖУ БОЛЬШЕ НЕ ВЫДАЁТСЯ. С task-021 всякое копирование обязано
 * отвечать человеку, а молчаливый `copy` этого не делает: он и был тем,
 * из-за чего копирование не отвечало ничем. Единственная дверь наружу —
 * `copyAndTell` ниже.
 */
async function copy(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    return false;
  }
}

/**
 * Сколько держится галочка «скопировано» рядом со скопированным.
 *
 * Живёт здесь, а не в экранах: до этого число стояло в приглашении своей
 * копией, и вторая появилась бы у моста. Полторы секунды — столько же,
 * сколько висит плашка.
 */
export const ГАЛОЧКА_МС = 1500;

/** Что сказать, когда браузер не дал. Строка одна на оба места. */
export const NOT_COPIED = "Браузер не дал скопировать. Выделите строку и скопируйте сами.";

/**
 * Скопировать и сказать об этом плашкой (Р-028).
 *
 * ⚠️ ОТКАЗ ТОЖЕ УХОДИТ В ПЛАШКУ, А НЕ В ТИШИНУ. Соблазн показывать
 * только успех велик — но человек, у которого буфер закрыт настройками,
 * увидел бы ровно то же, что и раньше: ничего. Он бы решил, что
 * скопировалось, и вставил бы чужое.
 *
 * Возвращает исход: местам, у которых есть свой знак (галочка на блоке
 * кода), он всё ещё нужен.
 */
export async function copyAndTell(text: string, message: string): Promise<boolean> {
  const ok = await copy(text);
  toast(ok ? message : NOT_COPIED);
  return ok;
}

/**
 * Скопировать молча, а сказать — только если не вышло.
 *
 * ⚠️ ЭТО НЕ ОБХОД ПРАВИЛА «КОПИРОВАНИЕ ОБЯЗАНО ОТВЕЧАТЬ», А ЕГО ВТОРАЯ
 * ФОРМА. Правило требует ответа человеку, а не именно плашки. Там, где
 * рядом со скопированным загорается галочка, ответ уже дан: плашка
 * говорит то же самое третий раз и закрывает собой то, на что человек
 * смотрит.
 *
 * Отказ остаётся плашкой всегда: галочки при отказе нет, и молчание
 * снова стало бы «решил, что скопировалось».
 */
export async function copyQuietly(text: string): Promise<boolean> {
  const ok = await copy(text);
  if (!ok) toast(NOT_COPIED);
  return ok;
}
