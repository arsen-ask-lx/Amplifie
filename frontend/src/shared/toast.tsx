import { useSyncExternalStore } from "react";

/**
 * Всплывающая плашка: «сделано» одной строкой (Р-028).
 *
 * ⚠️ РАЗМЕРЫ И СРОКИ СНЯТЫ С КЛИЕНТА ТЕЛЕГРАМА, А НЕ ВЫДУМАНЫ. В их
 * `lib_ui` это `defaultToast`: отступы 19 по бокам, 13 сверху и 12 снизу,
 * скругление 8, ширина не больше 480, появление 200 мс, угасание 1000,
 * жизнь 1500.
 *
 * ⚠️ ПО ЦЕНТРУ ОКНА, ПО ОБЕИМ ОСЯМ — И ЭТО ПРОВЕРЕНО ПО ИХ КОДУ, А НЕ
 * ПО ПАМЯТИ. В `toast_widget.cpp` при `RectPart::None` плашка ставится
 * в `middle`, то есть ровно в середину родителя; родителя назначает
 * `main_window.cpp` строкой `Toast::SetDefaultParent(_body)`, а `_body` —
 * это всё окно, вместе с их левой колонкой чатов. Значит и у них плашка
 * стоит НЕ по центру переписки, а по центру окна, и смещена влево
 * относительно неё ровно так же, как у нас.
 *
 * Я успел согласиться подвинуть её в середину нашего `<main>` и откатил,
 * когда дочитал: «как в Телеграме» и «по центру чата» — разные вещи,
 * и выбрано первое.
 *
 * ⚠️ ОТСТУПЫ ОКРУГЛЕНЫ ДО НАШЕЙ СЕТКИ: 20 по бокам и 12 сверху и снизу
 * вместо их 19/13/12. Сетка кратна четырём и стережётся гейтом (`make
 * rhythm`), а разница в один пиксель невидима. Пробивать сетку числом
 * в скобках ради точного повторения чужого — это менять проверяемое
 * правило на непроверяемое совпадение.
 *
 * ⚠️ СВОЯ, А НЕ ИЗ БИБЛИОТЕКИ. У Radix плашка есть, но она про
 * уведомления с действиями: очередь, наведение, отмена, свой поставщик.
 * Нам нужна одна надпись без единой кнопки — зависимость вышла бы
 * дороже кода.
 *
 * ⚠️ МЫШЬ СКВОЗЬ НЕЁ ПРОХОДИТ. Плашка висит посреди ленты, то есть ровно
 * над репликами, по которым в этот момент щёлкают. Не пропускай она
 * нажатия — копирование делало бы чат на полторы секунды неотзывчивым,
 * и это заметили бы раньше, чем саму плашку.
 *
 * ⚠️ СОСТОЯНИЕ ЛЕЖИТ В МОДУЛЕ, А НЕ В КОНТЕКСТЕ. Плашку зовут из мест,
 * которые ничего не знают друг о друге: меню реплики, блок кода, окно
 * приглашения, экран агента. Поставщик над всем приложением заставил бы
 * каждое из них знать про него; здесь же зовущему нужна одна функция.
 */

/** Тексты — те же, что у них (`lng_text_copied` и соседи). */
export const СКОПИРОВАНО = {
  текст: "Текст скопирован в буфер обмена.",
  код: "Код скопирован в буфер обмена.",
  ссылка: "Ссылка скопирована в буфер обмена.",
} as const;

const ЖИЗНЬ = 1500;
const УГАСАНИЕ = 1000;

interface Плашка {
  /** Своё число на каждый показ: по нему перезапускается появление. */
  id: number;
  text: string;
  /** Уже гаснет — значит прозрачность едет к нулю. */
  гаснет: boolean;
}

let текущая: Плашка | null = null;
let слушатели: Array<() => void> = [];
let счёт = 0;
let таймерУгасания: ReturnType<typeof setTimeout> | undefined;
let таймерСнятия: ReturnType<typeof setTimeout> | undefined;

function поставить(следующая: Плашка | null): void {
  текущая = следующая;
  for (const слушатель of слушатели) слушатель();
}

/**
 * Показать плашку.
 *
 * ⚠️ ВТОРАЯ ЗАМЕНЯЕТ ПЕРВУЮ, А НЕ ВСТАЁТ В ОЧЕРЕДЬ. Очередь означала бы,
 * что человек, скопировавший три раза подряд, четыре секунды смотрит
 * на отчёты о том, что и так помнит. Показываем последнее — оно и есть
 * то, что он только что сделал.
 */
export function toast(text: string): void {
  clearTimeout(таймерУгасания);
  clearTimeout(таймерСнятия);

  счёт += 1;
  поставить({ id: счёт, text, гаснет: false });

  таймерУгасания = setTimeout(() => {
    if (текущая) поставить({ ...текущая, гаснет: true });
  }, ЖИЗНЬ);
  таймерСнятия = setTimeout(() => поставить(null), ЖИЗНЬ + УГАСАНИЕ);
}

function подписаться(слушатель: () => void): () => void {
  слушатели = [...слушатели, слушатель];
  return () => {
    слушатели = слушатели.filter((один) => один !== слушатель);
  };
}

const прочитать = (): Плашка | null => текущая;

/**
 * Узел плашки. Ставится ОДИН РАЗ на всё приложение.
 *
 * ⚠️ `aria-live="polite"`, А НЕ РОЛЬ ОПОВЕЩЕНИЯ. Плашка сообщает об
 * успехе того, что человек только что сделал сам, — перебивать ею
 * чтение с экрана незачем. Тревожное `assertive` здесь было бы
 * назойливостью, а не заботой.
 */
export function Toasts() {
  const плашка = useSyncExternalStore(подписаться, прочитать, прочитать);

  return (
    <div
      aria-live="polite"
      className="pointer-events-none fixed inset-0 z-100 grid place-items-center"
    >
      {плашка ? (
        // ⚠️ КЛЮЧ ПО ЧИСЛУ ПОКАЗА: без него React переиспользовал бы узел,
        // и появление второй плашки не проигрывалось бы вовсе.
        <div
          key={плашка.id}
          style={{
            // Цвет объявлен ролью в `styles.css`, как и всё остальное:
            // литерал тема не перекрашивает, а гейт цвета его не пустит.
            background: "var(--toast-bg)",
            transitionDuration: `${УГАСАНИЕ}ms`,
          }}
          className={[
            "toast-in max-w-[480px] rounded-lg px-5 py-3",
            "text-body text-[var(--toast-fg)] transition-opacity",
            плашка.гаснет ? "opacity-0" : "opacity-100",
          ].join(" ")}
        >
          {плашка.text}
        </div>
      ) : null}
    </div>
  );
}
