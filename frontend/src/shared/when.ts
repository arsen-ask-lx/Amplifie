/**
 * Как в этом приложении пишутся время и даты.
 *
 * До task-012 форматов было четыре, объявленных в четырёх экранах, и ни
 * одного правила: лента писала месяц полным словом, доска — сокращённым,
 * договорённости — с часами, подключение — только часы. Каждый по
 * отдельности выглядел нормально; вместе — как небрежность. Это тот же
 * довод, по которому отступы стоят на сетке (Р-014).
 *
 * Форматов два, и у каждого свой вопрос:
 *   часы — «когда сегодня»: реплика в ленте, последняя связь моста;
 *   день — «какой это был день»: отбивка дня, дата задачи.
 *
 * Был и третий, «деньИЧас», — для договорённостей, где важен и день,
 * и час. Договорённости убраны, и формат ушёл следом: неиспользуемый
 * формат не ждёт своего часа, он ждёт, пока его применят не по делу.
 */

/** 14:05 */
export const часы = new Intl.DateTimeFormat("ru", { hour: "2-digit", minute: "2-digit" });

/** 7 сентября */
export const день = new Intl.DateTimeFormat("ru", { day: "numeric", month: "long" });
