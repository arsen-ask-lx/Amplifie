/**
 * Знак Amplifie.
 *
 * ⚠️ ЭТО SVG, НАРИСОВАННЫЙ ЗАНОВО, А НЕ КАРТИНКА. Владелец прислал форму
 * растром и сказал: «можешь цвета разные сделать». Растр покрасить нельзя —
 * ни темой, ни наведением, ни состоянием; он ещё и мылится на плотных
 * экранах и весит больше. Здесь тот же рисунок кривыми, и он берёт цвет
 * оттуда же, откуда весь остальной интерфейс.
 *
 * ⚠️ ЦВЕТ ПО УМОЛЧАНИЮ — `currentColor`. Значит знак красится тем же,
 * чем красится текст рядом с ним: сменилась тема — сменился и он, без
 * единой строки здесь. Двухцветный вариант включается признаком `дуо`:
 * тогда три узла берут акцент темы, а перемычки остаются чернильными.
 *
 * ЧТО ЗА ФОРМА. Три узла и связи между ними: два малых наверху сходятся
 * в перемычку, из неё дуга уходит к большому узлу внизу справа, а третий
 * малый висит слева. Это про то, чем занят продукт: разговор, из которого
 * вырастает работа. Толковать необязательно — важно, что знак узнаётся
 * с одного взгляда и не разваливается в шестнадцать пикселей.
 */
export function Logo({
  className,
  дуо = false,
}: {
  className?: string;
  /** Двухцветный: узлы акцентом, перемычки чернильным. */
  дуо?: boolean;
}) {
  const узлы = дуо ? "text-accent" : "";

  return (
    <svg viewBox="0 0 512 512" role="img" aria-label="Amplifie" className={className} fill="none">
      {/*
        ⚠️ СВЯЗКИ — ЛИНИИ С КРУГЛЫМИ КОНЦАМИ, А НЕ ЗАЛИТЫЕ ФИГУРЫ.
        Первая редакция рисовала их прямоугольниками, и на стыках
        с кругами получались ступеньки: видно с первого взгляда при любом
        размере. Линия с круглым концом стыкуется с кругом бесшовно
        по построению, а не по удаче — за это её и берут в знаках.
      */}
      <g stroke="currentColor" strokeWidth="72" strokeLinecap="round">
        {/* Седловина: два верхних узла тянутся друг к другу и провисают. */}
        <path d="M118 118C118 214 190 214 256 214C322 214 394 214 394 118" />
        {/* Дуга от седловины вниз-влево, к третьему малому узлу. */}
        <path d="M256 214C170 214 118 290 118 394" />
      </g>

      <g className={узлы} fill="currentColor">
        {/* Три малых узла и один большой. Радиусы разные намеренно:
            одинаковые читались бы как орнамент, а не как связь. */}
        <circle cx="118" cy="118" r="68" />
        <circle cx="394" cy="118" r="68" />
        <circle cx="118" cy="394" r="68" />
        <circle cx="350" cy="350" r="112" />
      </g>
    </svg>
  );
}
