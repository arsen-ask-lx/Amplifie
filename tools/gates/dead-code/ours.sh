#!/usr/bin/env sh
# Наш запуск гейта мёртвого кода.
#
# ⚠️ ОБЁРТКА, А НЕ ПРИСТАВКА В МАНИФЕСТЕ. Запись `ПЕРЕМЕННАЯ=значение
# команда` понятна только оболочкам POSIX: на Windows её пытается
# исполнить cmd, и гейт краснеет на исправном коде — худший вид отказа.
# Тот же довод, что у обёртки гейта цвета.
#
# ⚠️ ЗАЧЕМ ВЫКЛЮЧАТЕЛЬ. knip шестой версии разбирает файлы через oxc,
# а тот резервирует буфер в ШЕСТЬ ГИБИБАЙТ (2 ГиБ данных плюс 4 ГиБ
# выравнивания — числа из его же constants.js). На машине, где свободно
# меньше, вызов падает с `RangeError: Array buffer allocation failed`,
# и гейт не запускается вовсе. Гейт, который не может запуститься, —
# это гейт, которого нет: из-за него `make check` не был зелёным.
#
# `KNIP_DISABLE_RAW_TRANSFER` — выключатель самого knip, а не наша
# выдумка и не понижение версии. Разбор идёт медленнее на секунды
# и находит ровно то же самое.
#
# Проверено: с выключателем гейт нашёл неиспользуемый `potrace`
# и необъявленную зависимость `@lexical/link`, которая работала лишь
# потому, что подтянулась чужим пакетом.
KNIP_DISABLE_RAW_TRANSFER=1
export KNIP_DISABLE_RAW_TRANSFER

exec bash "$(dirname "$0")/../_native.sh" "${1:-.}" npx --yes knip@6 --directory "${1:-.}"
