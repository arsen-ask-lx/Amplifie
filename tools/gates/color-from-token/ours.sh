#!/usr/bin/env sh
# Наш запуск гейта цвета.
#
# ⚠️ ОБЁРТКА, А НЕ ПРИСТАВКА В МАНИФЕСТЕ. Запись `ПЕРЕМЕННАЯ=значение команда`
# ломается дважды: на Windows её пытается исполнить cmd, а прогонщик AQK
# передаёт строку не через оболочку — кавычки до него не доезжают, и команда
# падает с кодом 127. В файле же переменная просто есть.
#
# `styles|themes` — имена файлов-ИСТОЧНИКОВ значений: в них литерал законен,
# иначе токену неоткуда взяться. `themes.css` появился вместе с переносом
# тем, и без него гейт краснел на файле, который для того и существует.
AQK_COLOR_SOURCE="styles|themes"
export AQK_COLOR_SOURCE
exec bash "$(dirname "$0")/check.sh" "${1:-.}"
