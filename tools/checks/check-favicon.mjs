#!/usr/bin/env node
/**
 * Гейт: контур знака в значке вкладки совпадает с контуром в коде.
 *
 * ЗАЧЕМ. Знак живёт в двух файлах, и это вынужденно: значок вкладки
 * браузер запрашивает ДО того, как выполнится хоть одна строка нашего
 * кода, поэтому он обязан быть статическим файлом, а не компонентом.
 * Убрать вторую копию нельзя — значит нужно сторожить расхождение.
 *
 * Без сторожа это расходится молча и в самую неудобную сторону: знак
 * поправят в интерфейсе, а на вкладке останется прежний, и заметит это
 * не разработчик, а тот, у кого открыто двадцать вкладок.
 *
 * Сравнивается только сам контур (`d`), а не файл целиком: у значка
 * вкладки свои цвета под тему браузера, и это не расхождение, а разница
 * задач.
 */
import { readFileSync } from "node:fs";

const CODE = "frontend/src/shared/Logo.tsx";
const ICON = "frontend/public/favicon.svg";

/**
 * Контур из файла. Пробелы схлопнуты: перенос строки — не отличие.
 *
 * ⚠️ СОБИРАЕМ ВСЕ `d`, А НЕ ПЕРВЫЙ. Знак разошёлся на две части —
 * корону и шарик, — чтобы краситься от темы порознь: в компоненте это
 * два `path`, в значке вкладки по-прежнему один. Гейт, смотревший
 * только на первый, сравнивал корону с короной-и-шариком и краснел
 * на исправном знаке.
 */
function outline(path) {
  const text = readFileSync(path, "utf8");
  const found = [...text.matchAll(/d="([^"]+)"/gsu)].map((one) => one[1]);
  if (found.length === 0) {
    console.error(`${path} — не нашёл контур (атрибут d)`);
    console.error("  ПОЧИНИТЬ: контур знака обязан быть в обоих файлах.");
    process.exit(1);
  }
  return found.join(" ").replaceAll(/\s+/gu, " ").trim();
}

if (outline(CODE) !== outline(ICON)) {
  console.error("знак на вкладке разошёлся со знаком в интерфейсе");
  console.error(`  ${CODE} и ${ICON} держат разные контуры.`);
  console.error("  ПОЧИНИТЬ: скопируй значение d= из компонента в значок.");
  console.error("  Ведущий — компонент: его видно на экране каждый день.");
  process.exit(1);
}

console.log("значок вкладки и знак в интерфейсе — один контур — OK");
