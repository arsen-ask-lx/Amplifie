#!/usr/bin/env node

/**
 * Гейт: план задачи называет ЧИСЛА, которыми докажет свой успех.
 *
 * ЗАЧЕМ. Правило владельца 16.09.2026: работаем вертикальными срезами,
 * и перед началом среза называются числа, которые покажут, что срез удался.
 * Раздел «Чем докажем» у нас был с первого дня, но ничто не мешало написать
 * туда «убедимся, что работает быстро» — и такой план не отличить от плана
 * без критериев вовсе.
 *
 * ЧТО ИМЕННО ПРОВЕРЯЕТ. В плане есть раздел доказательств, и в нём есть
 * хотя бы одно число. Это грубая мера, и она названа грубой: гейт не умеет
 * отличить осмысленное число от бессмысленного. Он ловит ровно один класс —
 * доказательство словами вместо доказательства числом, — и этого достаточно,
 * чтобы заставить думать о числах ДО кода.
 *
 * ⚠️ ХРАПОВИК, А НЕ ЗАПРЕТ. Планов у нас восемь десятков, и часть старых
 * написана до правила. Заставлять переписывать историю нельзя: сделанный
 * план — запись о случившемся. Поэтому гейт считает планы без чисел и держит
 * их число под храповиком: новых появиться не может, старые уходят сами,
 * когда до них доходят руки.
 *
 * Запуск: make proof
 */

import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

const TASKS = "dock/tasks";
const RATCHET = "tools/ratchets/plans-without-proof.txt";

/** Как называется раздел доказательств. Формулировки разных лет. */
const PROOF_HEADING = /(чем\s+докажем|чем\s+доказано|как\s+проверим)/iu;

/**
 * Сколько строк после заголовка считаем разделом.
 *
 * Не до следующего заголовка: у части планов доказательства идут списком
 * без своего заголовка, и упереться в разметку значило бы мерить разметку,
 * а не содержание.
 */
const WINDOW = 40;

/** Есть ли в разделе доказательств хоть одно число. */
function provenByNumber(text) {
  const lines = text.split("\n");
  for (let n = 0; n < lines.length; n++) {
    if (!PROOF_HEADING.test(lines[n])) continue;
    // ⚠️ СО СЛЕДУЮЩЕЙ СТРОКИ, А НЕ С ЗАГОЛОВКА. Заголовок часто пронумерован
    // («## 4. Чем докажем»), и эта четвёрка засчитывалась за доказательство.
    // Поймано подсаженным нарушением при заводке гейта: план
    // с одними словами в доказательствах проходил зелёным.
    const section = lines.slice(n + 1, n + 1 + WINDOW).join("\n");
    // Номера планов и ссылок числами не считаем: «task-067» и «Р-029»
    // не доказывают ничего.
    const cleaned = section
      .replace(/task-\d+/giu, "")
      .replace(/[РрPp]-\d+/gu, "")
      .replace(/[ДдDd]-\d+/gu, "")
      .replace(/П-\d+/gu, "")
      .replace(/\d{2}\.\d{2}\.\d{4}/gu, "");
    if (/\d/u.test(cleaned)) return true;
  }
  return false;
}

function allowed() {
  try {
    return Number(readFileSync(RATCHET, "utf8").trim());
  } catch {
    throw new Error(
      `нет храповика ${RATCHET}\n` +
        `  ПОЧИНИТЬ: запусти гейт, посчитай планы без чисел и запиши их число —\n` +
        `  оно станет потолком, который можно только опускать.`,
    );
  }
}

const plans = readdirSync(TASKS).filter((one) => one.startsWith("task-") && one.endsWith(".md"));
const wordy = plans.filter((one) => !provenByNumber(readFileSync(join(TASKS, one), "utf8")));
const limit = allowed();

console.log(`планов ${plans.length}, из них без чисел в доказательствах ${wordy.length}`);

if (wordy.length > limit) {
  const fresh = wordy.slice(-5).join("\n    ");
  console.error(
    `\nпланов без чисел стало больше: ${wordy.length} при разрешённых ${limit}.\n` +
      `  ПОЧИНИТЬ: в разделе «Чем докажем» назови ЧИСЛА, а не слова — сколько\n` +
      `  запросов к базе, какая доля доставленных, 0.99 ответа, сколько строк\n` +
      `  прочитано. Рамки и примеры: dock/reference/критерии-успеха-и-замеры.md\n` +
      `  Вот последние из тех, что гейт не засчитал:\n    ${fresh}`,
  );
  process.exit(1);
}

if (wordy.length < limit) {
  console.error(
    `\nстало лучше, чем записано: ${wordy.length} против ${limit}.\n` +
      `  ПОЧИНИТЬ: опусти храповик ${RATCHET} до нового числа — иначе завтра\n` +
      `  возврат к старому пройдёт незамеченным.`,
  );
  process.exit(1);
}

console.log("планы доказываются числами — OK");
