/**
 * Нарезка потока SSE на события — так, как её делает `EventSource`.
 *
 * ⚠️ КУСОК ИЗ СОКЕТА — НЕ СОБЫТИЕ (task-091). Под нагрузкой в один
 * `read()` приезжают два события или половина одного. Считать кусок
 * событием значит терять посылки и догонять там, где браузер не догоняет.
 *
 * Разделитель — пустая строка `\n\n`: так пишет наш сервер
 * (`routes/stream.ts`). `\r\n` из спецификации SSE здесь не разбирается —
 * прибор говорит только с нашим сервером.
 */

/**
 * Отдаёт законченные события с данными и недочитанный хвост,
 * который надо приклеить к следующему куску.
 */
export function framed(buffer) {
  const parts = buffer.split("\n\n");
  const rest = parts.pop() ?? "";
  return { events: parts.filter((one) => one.includes("data:")), rest };
}
